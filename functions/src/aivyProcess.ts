/**
 * e.g. "ramesh ka 200000 baaki hai 10 din baad lena hai" → client, amount, days
 */
function tryExtractManualCollectionReminder(
  userText: string,
): {
  client: string;
  displayClient: string;
  amount: number;
  days: number;
} | null {
  const t = userText;
  const lower = t.toLowerCase();
  if (isDispatchRecordText(userText) || isRuleQuotationText(userText)) {
    return null;
  }
  if (
    isTodayOrderStatsQuestion(userText) ||
    isDispatchStatsQuestion(userText) ||
    isDispatchAggregateCountQuestion(userText)
  ) {
    return null;
  }
  const { client, amount: fb } = extractRuleClientAndAmount(t);
  if (!client || client === "Unknown") {
    return null;
  }
  const displayClient = capitalizeName(client);
  const dayM = lower.match(
    /(\d{1,3})\s*(?:din|day|dinon)(?:\s*(?:baad|ke\s*baad|me|mein|bad))?\b/,
  );
  let days = 0;
  if (dayM) {
    const d = parseInt(dayM[1]!, 10);
    if (d >= 1 && d <= 365) {
      days = d;
    }
  }
  if (days === 0) {
    const en = lower.match(
      /(?:after|follow[\s-]?up|follow)\s*(\d{1,3})\s*days?/i,
    );
    if (en) {
      const d2 = parseInt(en[1]!, 10);
      if (d2 >= 1 && d2 <= 365) {
        days = d2;
      }
    }
  }
  if (days === 0) {
    return null;
  }
  const baaki1 = lower.match(
    /([₹,.\d]+)\s*(?:ka|k)?\s*(?:baaki|baki|due|outstanding|bacha|bacha|pending|collect)/,
  );
  const baaki2 = lower.match(
    /(?:baaki|baki|outstanding|due|pending|bacha|collect|vasool).{0,30}?([₹,.\d]+)/,
  );
  let amount = 0;
  if (baaki1) {
    amount = coalesceNumber(baaki1[1]!);
  } else if (baaki2) {
    amount = coalesceNumber(baaki2[1]!);
  } else {
    const noComma = t.replace(/,/g, "");
    const matches = noComma.match(/\d+(?:[,\d]*\d+)?/g) ?? [];
    const nums = matches
      .map((x) => coalesceNumber(x))
      .filter((n) => n > 0 && n !== days);
    amount = nums.length > 0 ? Math.max(...nums) : coalesceNumber(String(fb));
  }
  if (!Number.isFinite(amount) || amount <= 0) {
    return null;
  }
  return { client, displayClient, amount, days };
}

function extractManualClientDisplayName(userText: string): string | null {
  const t = userText.trim();
  const mU = t.match(/^([\p{L}][\p{L}0-9 .]{1,50}?)\s+ka\s+/u);
  if (mU) {
    const name = mU[1]!.replace(/\s+/g, " ").trim();
    const low = name.toLowerCase();
    if (name.length >= 2 && !RULE_CLIENT_STOPWORDS.has(low)) {
      return name;
    }
  }
  const { client } = extractRuleClientAndAmount(userText);
  if (client && client !== "Unknown") {
    return client;
  }
  return null;
}

function extractManualPaymentInrAmount(userText: string): number {
  const lower = userText.toLowerCase();
  const lac = lower.match(/(\d+(?:[.,]\d+)?)\s*(?:lakh|lac|lacs|lakhs)\b/);
  if (lac) {
    const v = parseFloat(lac[1]!.replace(",", "."));
    if (Number.isFinite(v) && v > 0) {
      return Math.round(v * 100000);
    }
  }
  const cro = lower.match(/(\d+(?:[.,]\d+)?)\s*(?:crore|crores|karod)\b/);
  if (cro) {
    const v = parseFloat(cro[1]!.replace(",", "."));
    if (Number.isFinite(v) && v > 0) {
      return Math.round(v * 10000000);
    }
  }
  const baaki1 = lower.match(
    /([₹,.\d]+)\s*(?:ka|k)?\s*(?:baaki|baki|due|outstanding|bacha|pending|collect)/,
  );
  const baaki2 = lower.match(
    /(?:baaki|baki|outstanding|due|pending|bacha|collect|vasool).{0,30}?([₹,.\d]+)/,
  );
  let amount = 0;
  if (baaki1) {
    amount = coalesceNumber(baaki1[1]!);
  } else if (baaki2) {
    amount = coalesceNumber(baaki2[1]!);
  }
  if (amount > 0) {
    return amount;
  }
  const dayM = lower.match(
    /(\d{1,3})\s*(?:din|day|dinon)(?:\s*(?:baad|ke\s*baad|me|mein|bad))?\b/,
  );
  let dayHint: number | null = null;
  if (dayM) {
    const d0 = parseInt(dayM[1]!, 10);
    if (d0 >= 1 && d0 <= 365) {
      dayHint = d0;
    }
  }
  const noComma = userText.replace(/,/g, "");
  const matches = noComma.match(/\d+(?:[,\d]*\d+)?/g) ?? [];
  const nums = matches
    .map((x) => coalesceNumber(x))
    .filter((n) => n > 0 && (dayHint == null || n !== dayHint));
  if (nums.length > 0) {
    return Math.max(...nums);
  }
  const { amount: fb } = extractRuleClientAndAmount(userText);
  return coalesceNumber(fb);
}

/**
 * Manual collection: client + amount + payment/baaki/due intent.
 * When no relative day phrase is found, [days] is 0 (due today 10:00 in user zone), not a 30-day default.
 */
function tryExtractManualPaymentForFirestore(userText: string): {
  displayClient: string;
  amount: number;
  days: number;
} | null {
  if (isDispatchRecordText(userText) || isRuleQuotationText(userText)) {
    return null;
  }
  if (isRuleOrderCreateText(userText)) {
    return null;
  }
  if (
    isTodayOrderStatsQuestion(userText) ||
    isDispatchStatsQuestion(userText) ||
    isDispatchAggregateCountQuestion(userText)
  ) {
    return null;
  }
  const lower = userText.toLowerCase();
  const hasPaymentCue =
    /\b(baaki\s*hai|baki\s*hai|baaki|baki|due|dues|payment\s+due|lena\s*hai|lene|lenaa|vasool|vasuli|bhugtan|outstanding|collect|paisa|paise|udhaar|udha|उधार|₹|rupee)\b/i.test(
      lower,
    ) ||
    /\b(payment|pay|manual)\b/i.test(lower);
  const hasReminderCue =
    /\b(reminder|lagao|laga do|laga\s*do|set karo|schedule)\b/i.test(lower);
  if (!hasPaymentCue && !hasReminderCue) {
    return null;
  }
  if (hasReminderCue) {
    const hasPayWord = /\b(payment|pay|baki|baaki|due|vasool|₹|paisa|udhaar|उधार)\b/i.test(
      lower,
    );
    const hasAmountDigit = /[\d₹]/.test(userText);
    if (!hasPayWord && !hasAmountDigit) {
      return null;
    }
  }
  const rawClient = extractManualClientDisplayName(userText);
  if (!rawClient) {
    return null;
  }
  const displayClient = capitalizeName(rawClient);
  const amount = extractManualPaymentInrAmount(userText);
  if (!Number.isFinite(amount) || amount <= 0) {
    return null;
  }
  let days = 0;
  const dayM = lower.match(
    /(\d{1,3})\s*(?:din|day|dinon)(?:\s*(?:baad|ke\s*baad|me|mein|bad))?\b/,
  );
  if (dayM) {
    const d0 = parseInt(dayM[1]!, 10);
    if (d0 >= 1 && d0 <= 365) {
      days = d0;
    }
  } else {
    const en = lower.match(
      /(?:after|follow[\s-]?up|follow)\s+(\d{1,3})\s*days?/i,
    );
    if (en) {
      const d2 = parseInt(en[1]!, 10);
      if (d2 >= 1 && d2 <= 365) {
        days = d2;
      }
    }
  }
  if (
    /\bkal\b/i.test(lower) &&
    !/\bguzra|guzre|pichhl|yesterday|beet/i.test(lower)
  ) {
    days = 1;
  } else if (/\baaj\b|\btoday\b/i.test(lower)) {
    days = 0;
  }
  return { displayClient, amount, days };
}

async function recentManualPaymentDuplicate(
  uid: string,
  clientKey: string,
  amount: number,
  nowMs: number,
): Promise<boolean> {
  const db = getFirestore();
  const ref = db.collection("users").doc(uid).collection("payments");
  let docs: QueryDocumentSnapshot<DocumentData>[] = [];
  try {
    const snap = await ref.orderBy("createdAtMs", "desc").limit(40).get();
    docs = snap.docs;
  } catch (e) {
    logger.warn("recentManualPaymentDuplicate: orderBy failed, scanning", {
      err: e instanceof Error ? e.message : String(e),
    });
    const snap = await ref.limit(120).get();
    docs = snap.docs;
  }
  for (const doc of docs) {
    const d = doc.data() as DocumentData;
    const ck = normalizeClientNameKey(
      String(
        (d as { clientKey?: string }).clientKey ??
          (d as { clientName?: string }).clientName ??
          d.client ??
          "",
      ),
    );
    if (ck !== clientKey) {
      continue;
    }
    if (Math.abs(Number(d.amount) - amount) > 0.01) {
      continue;
    }
    const cm = Number((d as { createdAtMs?: unknown }).createdAtMs);
    if (!Number.isFinite(cm)) {
      continue;
    }
    if (nowMs - cm <= 5000) {
      return true;
    }
  }
  return false;
}

