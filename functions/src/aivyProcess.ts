function extractQueryKeywords(text: string): string[] {
  const matches = text.toLowerCase().match(/[a-z0-9]+/g) ?? [];
  const unique = new Set<string>();
  for (const token of matches) {
    if (token.length < 3) continue;
    if (RELEVANCE_STOPWORDS.has(token)) continue;
    unique.add(token);
  }
  return [...unique];
}

function lineMatchesKeywords(line: string, keywords: string[]): boolean {
  if (keywords.length === 0) {
    return false;
  }
  const lowered = line.toLowerCase();
  return keywords.some((keyword) => lowered.includes(keyword));
}

function formatMemoryTs(ms: number, zone: string): string {
  if (!Number.isFinite(ms) || ms <= 0) {
    return "unknown-time";
  }
  const dt = DateTime.fromMillis(ms).setZone(zone || "UTC");
  if (!dt.isValid) {
    return "unknown-time";
  }
  return dt.toFormat("dd LLL yyyy, h:mm a");
}

async function buildRecentMemoryContext(
  uid: string,
  timeContext: TimeContext,
  userQuery: string,
): Promise<string> {
  const db = getFirestore();
  const zone = timeContext.timezone || "UTC";
  const keywords = extractQueryKeywords(userQuery);

  try {
    const quotesRef = db.collection("users").doc(uid).collection("quotations");
    const entriesRef = db.collection("users").doc(uid).collection("entries");
    const tasksRef = db.collection("users").doc(uid).collection("tasks");

    const [quotesSnap, entriesSnap, tasksSnap] = await Promise.all([
      quotesRef.orderBy("createdAtMs", "desc").limit(20).get(),
      entriesRef.orderBy("createdAtMs", "desc").limit(20).get(),
      tasksRef.orderBy("createdAtMs", "desc").limit(20).get(),
    ]);

    const quoteLines = quotesSnap.docs.map((doc) => {
      const d = doc.data();
      const ms = Number(d.createdAtMs ?? 0);
      const when = formatMemoryTs(ms, zone);
      const client = safeSingleLine(d.clientName || "Unknown client");
      const amount = Number(d.amount);
      const amountLabel = Number.isFinite(amount) ? `₹${formatInrAmount(amount)}` : "unknown";
      return `- ${when} | client=${client} | amount=${amountLabel}`;
    });

    const entryLines = entriesSnap.docs
      .map((doc) => doc.data())
      .filter((d) => String(d.status ?? "").toLowerCase() === "completed")
      .map((d) => {
        const ms = Number(d.createdAtMs ?? 0);
        const when = formatMemoryTs(ms, zone);
        const memoryCategory = safeSingleLine(d.memoryCategory || "general");
        const summary = safeSingleLine(d.summary || d.rawInput || "").slice(0, 180);
        return `- ${when} | memoryCategory=${memoryCategory} | ${summary || "(no summary)"}`;
      });

    const taskLines = tasksSnap.docs.map((doc) => {
      const d = doc.data();
      const ms = Number(d.createdAtMs ?? 0);
      const when = formatMemoryTs(ms, zone);
      const status = safeSingleLine(d.status || "unknown");
      const title = safeSingleLine(d.title || d.message || d.text || "").slice(0, 180);
      return `- ${when} | status=${status} | ${title || "(no title)"}`;
    });

    const filteredQuoteLines = keywords.length > 0
      ? quoteLines.filter((line) => lineMatchesKeywords(line, keywords))
      : quoteLines;
    const filteredEntryLines = keywords.length > 0
      ? entryLines.filter((line) => lineMatchesKeywords(line, keywords))
      : entryLines;
    const filteredTaskLines = keywords.length > 0
      ? taskLines.filter((line) => lineMatchesKeywords(line, keywords))
      : taskLines;

    const lines: string[] = [];
    lines.push("[Recent quotations]");
    lines.push(...(filteredQuoteLines.length ? filteredQuoteLines.slice(0, 8) : ["- none"]));
    lines.push("");
    lines.push("[Recent entries]");
    lines.push(...(filteredEntryLines.length ? filteredEntryLines.slice(0, 8) : ["- none"]));
    lines.push("");
    lines.push("[Recent tasks]");
    lines.push(...(filteredTaskLines.length ? filteredTaskLines.slice(0, 8) : ["- none"]));

    return lines.join("\n");
  } catch (error) {
    logger.warn("buildRecentMemoryContext failed; continuing without memory context", {
      uid,
      error: error instanceof Error ? error.message : String(error),
    });
    return "";
  }
}

function extractGoalRecord(
  payload: Record<string, unknown>,
  timeContext: TimeContext,
): GoalRecordPayload | undefined {
  const raw = payload.goalRecord;
  if (raw === null || raw === undefined || typeof raw !== "object") {
    return undefined;
  }
  const r = raw as Record<string, unknown>;
  const amount = Number(r.targetAmount);
  if (Number.isNaN(amount) || amount <= 0) {
    return undefined;
  }
  let monthKey = typeof r.monthKey === "string" ? r.monthKey.trim() : "";
  if (!/^\d{4}-\d{2}$/.test(monthKey)) {
    monthKey =
      timeContext.todayDate.length >= 7 ? timeContext.todayDate.slice(0, 7) : "";
  }
  if (!/^\d{4}-\d{2}$/.test(monthKey)) {
    const d = DateTime.fromISO(timeContext.nowIso, { setZone: true });
    monthKey = d.isValid ? d.toFormat("yyyy-MM") : "";
  }
  if (!monthKey) {
    return undefined;
  }
  const title =
    typeof r.title === "string" && r.title.trim().length > 0
      ? r.title.trim()
      : "Monthly target";
  const currency =
    typeof r.currency === "string" && r.currency.trim().length > 0
      ? r.currency.trim()
      : "INR";
  const period =
    typeof r.period === "string" && r.period.trim().length > 0
      ? r.period.trim()
      : "month";
  return { title, targetAmount: amount, currency, period, monthKey };
}

function normalizePgplIntent(raw: string): AivyPgplIntent {
  const v = raw.toLowerCase().trim();
  if (
    v === "job_new" ||
    v === "job_dispatch" ||
    v === "payment_due" ||
    v === "report_request"
  ) {
    return v;
  }
  return "general";
}

function extractJobRecordFromPayload(
  payload: Record<string, unknown>,
): JobRecordPayload {
  const raw = payload.jobRecord;
  if (!raw || typeof raw !== "object") {
    return { ...EMPTY_JOB_RECORD };
  }
  const r = raw as Record<string, unknown>;
  const client = toString(r.client);
  const amount = Number(r.amount);
  const invoiceAmount = Number(r.invoiceAmount);
  const statusRaw = toString(r.status).toLowerCase();
  const status: "pending" | "dispatched" =
    statusRaw === "dispatched" ? "dispatched" : "pending";
  const amt = Number.isFinite(amount) ? amount : 0;
  const inv = Number.isFinite(invoiceAmount) ? invoiceAmount : amt;
  return {
    client,
    amount: amt,
    status,
    invoiceAmount: inv,
  };
}

function extractPaymentRecordFromPayload(
  payload: Record<string, unknown>,
  timeContext: TimeContext,
  intent: AivyPgplIntent,
): PaymentRecordPayload {
  void timeContext;
  const raw = payload.paymentRecord;
  const r =
    raw && typeof raw === "object" ? (raw as Record<string, unknown>) : {};
  const client = toString(r.client);
  const amount = Number(r.amount);
  let dueDateIso = toString(r.dueDateIso);
  if (!DateTime.fromISO(dueDateIso, { setZone: true }).isValid) {
    dueDateIso = "";
  }
  if (intent === "payment_due") {
    return {
      client,
      amount: Number.isFinite(amount) ? amount : 0,
      dueDateIso,
    };
  }
  return {
    client,
    amount: Number.isFinite(amount) ? amount : 0,
    dueDateIso,
  };
}

function sanitizeModelResponse(
  payload: Record<string, unknown>,
  timeContext: TimeContext,
): AivyProcessResponse {
  const intent = normalizePgplIntent(toString(payload.intent));
  const jobRecord = extractJobRecordFromPayload(payload);
  const paymentRecord = extractPaymentRecordFromPayload(
    payload,
    timeContext,
    intent,
  );
  const summary = toString(payload.summary);
  const actionItems = toActionItemStrings(payload.actionItems);
  const keyPoints = toStringList(payload.keyPoints);
  const followUpSuggestions = toFollowUps(payload.followUpSuggestions);
  const reminderSuggestions = toReminders(payload.reminderSuggestions);
  const assistantReplyRaw =
    toString(payload.message) ||
    toString(payload.userReply) ||
    toString(payload.assistantReply);
  let reply =
    cleanUserFacingReply(assistantReplyRaw) ||
    buildFallbackReply({
      summary,
      actionItems,
      reminderSuggestions,
    });
  reply = sanitizeUserFacingText(reply);
  if (!reply.trim()) {
    reply =
      reminderSuggestions.length > 0
        ? "Theek hai — reminder set ho gaya."
        : summary.trim()
          ? "Note kar liya."
          : "";
  }
  if (!reply.trim()) {
    reply = "Theek hai.";
  }

  const goalRecord = extractGoalRecord(payload, timeContext);
  const transcript = toString(payload.transcript);

  return {
    intent,
    jobRecord,
    paymentRecord,
    contextType: normalizeContextType(toString(payload.contextType)),
    category: normalizeCategory(toString(payload.category)),
    memoryCategory: normalizeMemoryCategory(toString(payload.memoryCategory)),
    clientName: toString(payload.clientName),
    summary,
    keyPoints,
    actionItems,
    followUpSuggestions,
    reminderSuggestions,
    assistantReply: reply,
    userReply: reply,
    message: reply,
    ...(transcript ? { transcript } : {}),
    ...(goalRecord ? { goalRecord } : {}),
  };
}

function toString(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

function toStringList(value: unknown): string[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .map((item) => (typeof item === "string" ? item.trim() : ""))
    .filter((item) => item.length > 0);
}

/** Maps Gemini actionItems (objects with title/priority or legacy strings) to string[]. */
function toActionItemStrings(value: unknown): string[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .map((item) => {
      if (typeof item === "string") {
        const s = item.trim();
        return s.length > 0 ? s : "";
      }
      if (typeof item === "object" && item !== null) {
        const record = item as Record<string, unknown>;
        return toString(record.title);
      }
      return "";
    })
    .filter((item) => item.length > 0);
}

function toFollowUps(value: unknown): FollowUpSuggestion[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .map((item) => {
      const record =
        typeof item === "object" && item !== null
          ? (item as Record<string, unknown>)
          : {};
      return {
        when: toString(record.when),
        reason: toString(record.reason),
      };
    })
    .filter((item) => item.when || item.reason);
}

function toReminders(value: unknown): ReminderSuggestion[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .map((item) => {
      const record =
        typeof item === "object" && item !== null
          ? (item as Record<string, unknown>)
          : {};
      const rawIso = (
        toString(record.scheduledAtIso) || toString(record.time)
      ).trim();
      const isAuto =
        record.isAutoGenerated === true ||
        String(record.isAutoGenerated) === "true";
      const title =
        toString(record.title) || (rawIso.length > 0 ? "Reminder" : "");
      const orderAmt = record.orderAmountInr;
      const orderAmtN =
        typeof orderAmt === "number"
          ? orderAmt
          : typeof orderAmt === "string"
            ? Number(orderAmt)
            : NaN;
      const rt = toString(record.reminderType).toLowerCase();
      const reminderTypeParsed: "payment_followup" | "manual_payment" | undefined =
        rt === "payment_followup" || rt === "manual_payment" ? rt : undefined;
      return {
        title,
        timeHint: toString(record.timeHint),
        priority: normalizePriority(toString(record.priority)),
        scheduledAtIso: rawIso.length > 0 ? rawIso : undefined,
        isAutoGenerated: isAuto ? true : undefined,
        reminderType: reminderTypeParsed,
        orderId: toString(record.orderId) || undefined,
        orderAmountInr: Number.isFinite(orderAmtN) ? orderAmtN : undefined,
        displayClientName: toString(record.displayClientName) || undefined,
        note: toString(record.note) || undefined,
        paymentId: toString(record.paymentId) || undefined,
      };
    })
    .filter((item) => item.title.length > 0);
}

function normalizePriority(priority: string): "high" | "medium" | "low" {
  const lowered = priority.toLowerCase();
  if (lowered === "high" || lowered === "low" || lowered === "medium") {
    return lowered;
  }
  return "medium";
}

function normalizeContextType(value: string): string {
  const lowered = value.toLowerCase();
  const valid = new Set(["task", "reminder", "note", "mixed"]);
  if (valid.has(lowered)) {
    return lowered;
  }
  return "note";
}

function normalizeCategory(value: string): string {
  const lowered = value.toLowerCase();
  const valid = new Set(["client", "work", "personal", "general"]);
  if (valid.has(lowered)) {
    return lowered;
  }
  return "general";
}

function normalizeMemoryCategory(value: string): string {
  const lowered = value.toLowerCase();
  if (lowered === "reminder") {
    return "task";
  }
  const valid = new Set([
    "quotation",
    "task",
    "note",
    "general",
    "goal",
  ]);
  if (valid.has(lowered)) {
    return lowered;
  }
  return "general";
}

function buildFallbackReply({
  summary,
  actionItems,
  reminderSuggestions,
}: {
  summary: string;
  actionItems: string[];
  reminderSuggestions: ReminderSuggestion[];
}): string {
  if (reminderSuggestions.length > 0) {
    const t = reminderSuggestions[0].title;
    return t
      ? `Reminder noted for "${t}".`
      : "I've noted that down.";
  }
  if (actionItems.length > 0) {
    return `Added "${actionItems[0]}" to your task list.`;
  }
  if (summary.length > 0) {
    return "Noted.";
  }
  return "I've noted that down.";
}

