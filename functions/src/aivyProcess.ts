function dueMsFromValidPaymentIsoString(iso: string): number | null {
  const t = (iso || "").trim();
  if (!t) {
    return null;
  }
  const dt = DateTime.fromISO(t, { setZone: true });
  return dt.isValid ? dt.toMillis() : null;
}

/**
 * Fill payment due: rule-based text first, then model client/amount with explicit due only (no +30d default).
 * Payment rows always use the resulting [dueMs] on the document.
 */
function coercePaymentDueForPersist(
  userText: string,
  timeContext: TimeContext,
  response: AivyProcessResponse,
): { client: string; amount: number; dueMs: number } | null {
  const rule = tryExtractManualPaymentForFirestore(userText);
  if (rule && rule.amount > 0) {
    const base = nowInUserZone(timeContext);
    const at = base
      .plus({ days: rule.days })
      .set({ hour: 10, minute: 0, second: 0, millisecond: 0 });
    const dueMs = at.isValid
      ? at.toMillis()
      : Date.now() + rule.days * 24 * 60 * 60 * 1000;
    return { client: rule.displayClient, amount: rule.amount, dueMs };
  }
  const pr = response.paymentRecord;
  const c0 = pr.client.trim();
  const a0 = Number(pr.amount);
  if (!c0 || !Number.isFinite(a0) || a0 <= 0) {
    return null;
  }
  const fromModel = dueMsFromValidPaymentIsoString(pr.dueDateIso);
  if (fromModel != null && fromModel > 0) {
    return { client: capitalizeName(c0), amount: a0, dueMs: fromModel };
  }
  const nowAnchor = nowInUserZone(timeContext);
  const atToday = nowAnchor.set({ hour: 10, minute: 0, second: 0, millisecond: 0 });
  const dueMs = atToday.isValid
    ? atToday.toMillis()
    : Date.now();
  return { client: capitalizeName(c0), amount: a0, dueMs };
}

/**
 * Persists PGPL job rows when JSON is trusted; [payment_due] always uses [createPaymentEntry] + rules (not gated on JSON).
 */
async function persistPgplDirectFirestore(
  uid: string,
  response: AivyProcessResponse,
  timeContext: TimeContext,
  userText: string,
  options: PersistPgplOptions,
): Promise<PersistPgplResult> {
  if (isDataDrivenIntent(response.intent)) {
    return {};
  }
  const { intent, jobRecord } = response;
  const db = getFirestore();
  const nowMs = Date.now();
  const trusted = options.fromStructuredModelJson;

  if (intent === "job_new") {
    if (!trusted) {
      return {};
    }
    const client = jobRecord.client.trim();
    if (!client) {
      logger.warn("persistPgplDirectFirestore job_new skipped: empty client", {
        uid,
      });
      return {};
    }
    await db
      .collection("users")
      .doc(uid)
      .collection("jobs")
      .add({
        client: jobRecord.client,
        amount: jobRecord.amount,
        status: "pending",
        invoiceAmount: jobRecord.invoiceAmount,
        createdAtMs: nowMs,
        updatedAtMs: nowMs,
      });
    logger.info("persistPgplDirectFirestore job_new written", { uid, client });
    return {};
  }

  if (intent === "job_dispatch") {
    if (!trusted) {
      return {};
    }
    const clientRaw =
      jobRecord.client.trim() || response.clientName.trim();
    if (!clientRaw) {
      logger.warn(
        "persistPgplDirectFirestore job_dispatch skipped: empty client",
        { uid },
      );
      return {};
    }
    const key = normalizeClientNameKey(clientRaw);
    const jobsRef = db.collection("users").doc(uid).collection("jobs");
    const pendingSnap = await jobsRef
      .where("status", "==", "pending")
      .limit(100)
      .get();
    const candidates = pendingSnap.docs
      .map((d) => ({ id: d.id, data: d.data() as Record<string, unknown> }))
      .sort(
        (a, b) =>
          (Number(b.data.createdAtMs) || 0) - (Number(a.data.createdAtMs) || 0),
      );
    let targetId: string | null = null;
    for (const { id, data } of candidates) {
      const c = String(data.client ?? "").trim();
      if (!c) continue;
      const ck = normalizeClientNameKey(c);
      if (ck === key) {
        targetId = id;
        break;
      }
    }
    if (!targetId) {
      logger.warn(
        "persistPgplDirectFirestore job_dispatch: no matching pending job",
        { uid, client: clientRaw },
      );
      return {};
    }
    const inv = Number.isFinite(jobRecord.invoiceAmount)
      ? jobRecord.invoiceAmount
      : Number.isFinite(jobRecord.amount)
        ? jobRecord.amount
        : 0;
    const days = extractPaymentDaysForDispatch(userText);
    const base = nowInUserZone(timeContext);
    const at = base
      .plus({ days })
      .set({ hour: 10, minute: 0, second: 0, millisecond: 0 });
    const paymentDueDateMs = at.toMillis();
    await jobsRef.doc(targetId).update({
      status: "dispatched",
      invoiceAmount: inv,
      updatedAtMs: nowMs,
      paymentStatus: "pending",
      paymentDueDate: Timestamp.fromMillis(paymentDueDateMs),
      paymentDueDateMs,
      paymentReminderCreated: true,
    });
    const payAmt = inv > 0 ? inv : (jobRecord.amount || 0);
    if (payAmt <= 0) {
      logger.warn("persistPgplDirectFirestore: gemini job_dispatch payment amount zero, no payment row", {
        uid,
        jobId: targetId,
      });
      logger.info("persistPgplDirectFirestore job_dispatch updated", { uid, jobId: targetId });
      return {};
    }
    const { id: pid } = await createPaymentEntry(uid, {
      clientName: capitalizeName(clientRaw),
      amount: payAmt,
      dueDateMs: paymentDueDateMs,
      source: "gemini",
      jobId: targetId,
      timeZoneForIso: timeContext.timezone?.trim() || "Asia/Kolkata",
    });
    // eslint-disable-next-line no-console
    console.log("REMINDER LINKED", { paymentId: pid, jobId: targetId });
    logger.info("persistPgplDirectFirestore job_dispatch updated", {
      uid,
      jobId: targetId,
      paymentId: pid,
    });
    return { geminiDispatchPaymentId: pid };
  }

  if (intent === "payment_due") {
    if (isPaymentQueryOnlyIntentText(userText)) {
      // eslint-disable-next-line no-console
      console.log("PAYMENT_INTENT", { kind: "query", blockCreate: "payment_due" });
      return {};
    }
    const coerced = coercePaymentDueForPersist(userText, timeContext, response);
    if (!coerced || !coerced.client || coerced.amount <= 0) {
      logger.warn("persistPgplDirectFirestore payment_due: could not resolve client+amount", {
        uid,
      });
      return {};
    }
    const { id: pid } = await createPaymentEntry(uid, {
      clientName: coerced.client,
      amount: coerced.amount,
      dueDateMs: coerced.dueMs,
      source: "gemini",
      timeZoneForIso: timeContext.timezone?.trim() || "Asia/Kolkata",
    });
    logger.info("persistPgplDirectFirestore payment_due written", {
      uid,
      client: coerced.client,
      paymentId: pid,
    });
    return {};
  }

  return {};
}

