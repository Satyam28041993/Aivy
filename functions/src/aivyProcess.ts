/** When the business marked the order as dispatched (canonical [dispatchDate], legacy [dispatchedAtMs]). */
function readOrderDispatchTimeMs(d: DocumentData): number {
  const dd = (d as { dispatchDate?: unknown }).dispatchDate;
  if (dd && typeof (dd as { toMillis?: () => number }).toMillis === "function") {
    const m = (dd as { toMillis: () => number }).toMillis();
    if (m > 0) {
      return m;
    }
  }
  const n = Number((d as { dispatchedAtMs?: unknown }).dispatchedAtMs);
  if (Number.isFinite(n) && n > 0) {
    return n;
  }
  return 0;
}

/**
 * Orders that were **explicitly** marked dispatched, with the mark instant in the wall-time
 * window. Prefers [dispatchDate]; legacy docs use [dispatchedAtMs] (deduped).
 */
async function queryOrdersDispatchedInRange(
  uid: string,
  startMs: number,
  endMs: number,
): Promise<QueryDocumentSnapshot<DocumentData>[]> {
  const db = getFirestore();
  const ref = db.collection("users").doc(uid).collection("orders");
  if (!Number.isFinite(startMs) || !Number.isFinite(endMs) || endMs < startMs) {
    return [];
  }
  const startTs = Timestamp.fromMillis(startMs);
  const endTs = Timestamp.fromMillis(endMs);
  const byDate = await ref
    .where("dispatchDate", ">=", startTs)
    .where("dispatchDate", "<=", endTs)
    .get();
  const byMs = await ref
    .where("dispatchedAtMs", ">=", startMs)
    .where("dispatchedAtMs", "<=", endMs)
    .get();
  const map = new Map<string, QueryDocumentSnapshot<DocumentData>>();
  const accept = (doc: QueryDocumentSnapshot<DocumentData>) => {
    const data = doc.data() as DocumentData;
    if (String(data.status ?? "").trim().toLowerCase() !== "dispatched") {
      return;
    }
    const t = readOrderDispatchTimeMs(data);
    if (t < startMs || t > endMs) {
      return;
    }
    if (!map.has(doc.id)) {
      map.set(doc.id, doc);
    }
  };
  for (const d of byDate.docs) {
    accept(d);
  }
  for (const d of byMs.docs) {
    const data = d.data() as DocumentData;
    if ((data as { dispatchDate?: unknown }).dispatchDate == null) {
      accept(d);
    }
  }
  return [...map.values()];
}

function normalizeAnalyticsText(text: string): string {
  return text
    .toLowerCase()
    .replace(/qoutation|qotation|quatation/g, "quotation")
    .replace(/\bdine\b/g, "din");
}

/**
 * "Value" (rupee sum) vs "count" for analytics. Dispatch + value must beat dispatch + count.
 */
function valueIntentWinsInAnalytics(t: string): boolean {
  if (/\b(kitne|kitni|how many|count|itne)\b/.test(t) && !/\bkitna\b/.test(t)) {
    if (/\b(quotation|quote|qtn)\b/.test(t)) {
      return false;
    }
    if (/\b(dispatch|bhej|bheja|ship|shipped)\b/.test(t)) {
      if (
        /\b(value|mulya|jama|₹|rupee|rs|amount|turnover|invoice|lakh|crore)\b/.test(
          t,
        ) ||
        /value\s*ka|kitna\s+value|value\s+kitna/.test(t)
      ) {
        return true;
      }
      return false;
    }
  }
  if (/\b(kitne|kitni)\b.*\b(quotation|quote)\b/.test(t)) {
    return false;
  }
  if (
    /\b(value|mulya|jama|turnover|invoice|kitna value|value ka|mulya|₹|rupee|rs\.?)\b/.test(
      t,
    ) ||
    /value\s*ka|kitna\s+value|dispatch\s+value|order\s+value|value.*dispatch|dispatch.*value/.test(
      t,
    )
  ) {
    if (/\b(only|just|sirf)\b.*\bcount\b/.test(t)) {
      return false;
    }
    return true;
  }
  if (
    /\bkitna\b/.test(t) &&
    !/\bkitne\b/.test(t) &&
    /\b(rupee|₹|lakh|crore|jama|mulya|value|ka|amount)\b/.test(t)
  ) {
    return true;
  }
  return false;
}

