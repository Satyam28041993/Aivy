function buildDailyStatusBlock(s: { oneLiner: string; fullText: string }): string {
  return `${s.oneLiner}\n\n${s.fullText}`.trim();
}

function formatRupeesLineAmount(n: number): string {
  return `₹${formatInrAmount(n)}`;
}

function formatClientAmountList(
  title: string,
  rows: Array<{ client: string; amount: number }>,
): string {
  if (rows.length === 0) {
    return title;
  }
  const lines = rows.map(
    (r, i) => `${i + 1}. ${r.client} — ${formatRupeesLineAmount(r.amount)}`,
  );
  return `${title}\n${lines.join("\n")}`;
}

function formatClientAmountDateList(
  title: string,
  rows: Array<{ client: string; amount: number; dueDateLabel: string }>,
): string {
  if (rows.length === 0) {
    return title;
  }
  const lines = rows.map((r, i) => {
    const amt = Number(r.amount ?? 0);
    const money =
      Number.isFinite(amt) && amt > 0 ? `${formatRupeesLineAmount(amt)} · ` : "";
    return `${i + 1}. ${r.client} — ${money}${(r.dueDateLabel || "").trim() || "—"}`;
  });
  return `${title}\n${lines.join("\n")}`;
}

