/**
 * System-only answer for creator / "who made you" questions. Never use Gemini.
 */
function isWhoCreatedYouQuestion(text: string): boolean {
  const t = text.trim().toLowerCase();
  if (t.length === 0 || t.length > 200) {
    return false;
  }
  if (
    /\b(who\s+made\s+you|who\s+created\s+you|who\s+is\s+your\s+creator)\b/.test(
      t,
    ) ||
    /\b(kisne\s+banaya|kisne\s+create|kisne\s+bnaya|kisne\s+banaaya)\b/.test(
      t,
    ) ||
    /\b(tumhe\s+kisne|aapko\s+kisne|tumhara\s+creator|your\s+creator)\b/.test(
      t,
    ) ||
    /\b(banaya\s+hai|banaaya\s+hai|create\s+kiya)\b.*\b(kisne|who)\b/.test(
      t,
    ) ||
    /\b(kisne|who)\b.*\b(banaya|banaaya|create)\b/.test(t)
  ) {
    return true;
  }
  return false;
}

/**
 * "Aaj kitne order" style questions — not "aaj X ka order aaya" (log line) or dispatch counts.
 * Requires an explicit question phrase so narrative "aaj mera order aaya" is not misfired.
 */
function isTodayOrderStatsQuestion(text: string): boolean {
  const t = text.toLowerCase();
  if (!/\b(aaj|aajke|aaj ke|today|aajka|aaj ka|abhi tak)\b/.test(t)) {
    return false;
  }
  if (!/\b(order|orders|aorder|booking|po|p\.?o\.?|purchase order)\b/.test(t)) {
    return false;
  }
  if (
    /\b(quotation|quotations|quote|qtn|क्वोट)\b/.test(t) &&
    !/\b(order|orders)\b/.test(t)
  ) {
    return false;
  }
  // Leave "aaj kitne order dispatch" to data-driven (dispatches_today) — not naya-order count.
  if (/\b(dispatch|dispatched|bhej|bheja|bheje|ship|shipped)\b/.test(t)) {
    return false;
  }
  if (
    !/\b(kitne|kitna|kitni|kya|count|how many|total|itne|list|bata|batao)\b/.test(
      t,
    ) &&
    !t.includes("?")
  ) {
    return false;
  }
  return true;
}

/**
 * "Aaj kitne / is month me kitna qoutation" style questions — not "X ko … ka
 * qoutation diya" (log line to save). Must run before [isRuleQuotationText] so
 * stats queries are not mistaken for a save-quotation rule.
 */
function isQuotationStatsQuestion(text: string): boolean {
  const t = text.trim().toLowerCase();
  if (t.length < 3) {
    return false;
  }
  const norm = normalizeAnalyticsText(t);
  const hasQuot =
    /(quotation|quotes?|qtn|क्वोट)/.test(norm) || /qoutation|qotation|quatation/.test(t);
  if (!hasQuot) {
    return false;
  }
  // Log: "sanjay ko 100000 ka qoutation diya" — has amount + diya; not a Q&A
  if (
    /\b(diya|diye|mila|aaya|aayi)\b/.test(t) &&
    /\d{2,}/.test(t) &&
    !/\b(kitne|kitna|kitni|batao|bata|kab|kya|count|list|naam|kaun)\b/.test(t)
  ) {
    return false;
  }
  if (
    !/\b(kitne|kitna|kitni|kya|count|how many|total|itne|list|bata|batao|jama|mulya|value|₹|rupee|naam|kaun|kab|aaj|aajke|aaj ke|today|aajka|aaj ka|abhi tak|kal|yesterday|is\s*maahine|is\s+mahine|is\s*month|this\s*month|current\s*month|poora mahina|pura month|is\s*hafte|is\s+week|this\s+week|pichhle|pichle)\b/i.test(
      t,
    ) &&
    !t.includes("?")
  ) {
    return false;
  }
  return true;
}

