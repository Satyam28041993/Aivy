/**
 * Personal/family data at `users/{uid}/memory/profile` (merge updates).
 * Loaded on every aivyProcess turn and merged into the Gemini USER_PROFILE block.
 */
export async function getUserMemory(uid: string): Promise<Record<string, unknown>> {
  try {
    const doc = await getFirestore()
      .collection("users")
      .doc(uid)
      .collection("memory")
      .doc(USER_MEMORY_PROFILE_DOC)
      .get();
    const data = doc.data();
    if (!data) {
      return {};
    }
    return { ...data } as Record<string, unknown>;
  } catch (e) {
    logger.warn("getUserMemory failed; using empty", {
      uid,
      err: e instanceof Error ? e.message : String(e),
    });
    return {};
  }
}

function deepMergeObjects(
  base: Record<string, unknown>,
  patch: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const k of Object.keys(patch)) {
    const bv = patch[k];
    const av = out[k];
    if (
      bv &&
      typeof bv === "object" &&
      !Array.isArray(bv) &&
      av &&
      typeof av === "object" &&
      !Array.isArray(av)
    ) {
      out[k] = deepMergeObjects(
        av as Record<string, unknown>,
        bv as Record<string, unknown>,
      );
    } else if (bv !== undefined) {
      out[k] = bv;
    }
  }
  return out;
}

/**
 * Merges partial profile data from Firestore into the canonical in-code profile.
 * Unknown top-level / family keys from storage still appear in the JSON block via
 * [buildProfileJsonForPrompt].
 */
function mergeFamilyMember(
  base: AivyFamilyMember,
  raw: unknown,
): AivyFamilyMember {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    return base;
  }
  const o = raw as Record<string, unknown>;
  const name =
    typeof o.name === "string" && o.name.trim() ? o.name.trim() : base.name;
  const dob = typeof o.dob === "string" && o.dob.trim() ? o.dob.trim() : base.dob;
  return { name, dob };
}

function mergeCanonicalProfileWithMemory(
  base: AivyUserProfile,
  m: Record<string, unknown>,
): AivyUserProfile {
  if (!m || Object.keys(m).length === 0) {
    return base;
  }
  const s = (k: string): string => {
    const v = m[k];
    return typeof v === "string" && v.trim() ? v.trim() : "";
  };
  const fam = m.family;
  const famObj: Record<string, unknown> =
    fam && typeof fam === "object" && !Array.isArray(fam)
      ? (fam as Record<string, unknown>)
      : {};
  return {
    name: s("name") || base.name,
    role: s("role") || base.role,
    company: s("company") || base.company,
    dob: s("dob") || base.dob,
    language: s("language") || base.language,
    family: {
      wife: mergeFamilyMember(base.family.wife, famObj.wife),
      daughter: mergeFamilyMember(base.family.daughter, famObj.daughter),
      son: mergeFamilyMember(base.family.son, famObj.son),
    },
  };
}

