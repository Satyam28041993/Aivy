async function runDataIntentQuery(
  uid: string,
  timeContext: TimeContext,
  intent: AivyDataIntent,
): Promise<AivyDataPayload> {
  const { start: dayStart, end: dayEnd } = todayStartEndMs(timeContext);
  const { start: monthStart, end: monthEnd } = currentMonthStartEndMs(timeContext);
  if (intent === "total_quotation_today") {
    const list = await queryQuotationIdsInRange(uid, dayStart, dayEnd);
    return { count: list.length };
  }
  if (intent === "quotation_names_today") {
    const list = await queryQuotationIdsInRange(uid, dayStart, dayEnd);
    const names = uniqueSortedNonEmpty(
      list.map((doc) => documentQuotationClientName(doc.data())),
    );
    return { count: names.length, names };
  }
  if (intent === "quotation_value_today") {
    const list = await queryQuotationIdsInRange(uid, dayStart, dayEnd);
    let total = 0;
    for (const q of list) {
      const d = q.data();
      const ms = documentCreatedMs(d);
      if (ms < dayStart || ms > dayEnd) {
        continue;
      }
      total += documentAmount(d);
    }
    return { totalAmount: total };
  }
  if (intent === "total_orders_today") {
    const list = await queryOrdersCreatedInRange(uid, dayStart, dayEnd);
    let total = 0;
    for (const o of list) {
      total += documentAmount(o.data());
    }
    return { count: list.length, totalAmount: total };
  }
  if (intent === "dispatches_today") {
    const jobs = await queryJobsDispatchedInRange(uid, dayStart, dayEnd);
    const orders = await queryOrdersDispatchedInRange(uid, dayStart, dayEnd);
    return { count: jobs.length + orders.length };
  }
  if (intent === "total_orders_month") {
    const list = await queryOrdersCreatedInRange(uid, monthStart, monthEnd);
    let total = 0;
    for (const o of list) {
      const d = o.data();
      const ms = documentCreatedMs(d);
      if (ms < monthStart || ms > monthEnd) {
        continue;
      }
      total += documentAmount(d);
    }
    return { totalAmount: total };
  }
  return {};
}

