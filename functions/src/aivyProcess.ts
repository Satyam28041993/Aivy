async function fetchGeminiGenerateContentWithRetry(
  geminiKey: string,
  body: string,
): Promise<Response> {
  let lastErr: unknown;
  for (let i = 0; i < 2; i++) {
    try {
      return await fetch(geminiEndpoint, {
        method: "POST",
        headers: googleGenerativeApiHeaders(geminiKey),
        body,
      });
    } catch (e) {
      lastErr = e;
      if (i === 1) {
        throw e;
      }
      logger.warn("Gemini fetch failed, retrying", {
        attempt: i + 1,
        err: e instanceof Error ? e.message : String(e),
      });
    }
  }
  throw lastErr;
}

function googleGenerativeApiHeaders(geminiApiKey: string): Record<string, string> {
  return {
    "Content-Type": "application/json",
    "x-goog-api-key": geminiApiKey,
  };
}

type GeminiGenerateContentResponse = {
  candidates?: Array<{
    content?: { parts?: Array<{ text?: string }> };
  }>;
};

function textFromGenerateContent(
  data: GeminiGenerateContentResponse,
): string {
  const parts = data.candidates?.[0]?.content?.parts;
  if (!parts?.length) {
    return "";
  }
  return parts
    .map((p) => (typeof p.text === "string" ? p.text : ""))
    .join("");
}

