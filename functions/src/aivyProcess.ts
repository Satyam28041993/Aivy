/**
 * Asking about dues (kitna / kab / kaun / list / dikha / due hai) — never a new payment create.
 * Does not match explicit entry lines parsed by [tryExtractManualPaymentForFirestore].
 */
function isPaymentQueryOnlyIntentText(s: string): boolean {
  if (tryExtractManualPaymentForFirestore(s) != null) {
    return false;
  }
  const t = s.toLowerCase();
  if (
    !/\b(payment|dues?|baki|baaki|udhaar|udha|vasool|vasuli|outstanding|lenaa|leni|lene|chuk|bhugtan|pay|due|collect)\b/i.test(
      t,
    )
  ) {
    return false;
  }
  return (
    /\b(kitna|kab|kaun|list|dikhao|dikha|dikhai|batao|bata|due\s+hai|kaun\s+se|kisko)\b/i.test(
      t,
    ) || /\bshow\s+(me\s+)?(the\s+)?(a\s+)?(payment|list|dues?)\b/i.test(t)
  );
}

/** Phrases like "manual payment due" (record entry) vs dashboard list queries. */
function isGenericPaymentDueIntentText(s: string): boolean {
  const t = s.toLowerCase().trim();
  if (t.length < 4) {
    return false;
  }
  if (isPaymentDueListQueryText(s) || isPaymentQueryOnlyIntentText(s)) {
    return false;
  }
  return /\b(manual\s+payment|payment\s+due|udhaar|udha|उधार|baaki\s*hai|baki\s*hai|kitna\s+baki|payment\s+lena|lena\s+hai|lene\s+hai)\b/.test(
    t,
  );
}

/** Cues of collection/udhaar without a full (client+amount) parse. */
function hasLoosePaymentCollectionIntent(userText: string): boolean {
  if (isDispatchRecordText(userText) || isRuleQuotationText(userText) || isRuleOrderCreateText(userText)) {
    return false;
  }
  if (
    isTodayOrderStatsQuestion(userText) ||
    isDispatchStatsQuestion(userText) ||
    isDispatchAggregateCountQuestion(userText)
  ) {
    return false;
  }
  if (isPaymentDueListQueryText(userText) || isPaymentQueryOnlyIntentText(userText)) {
    return false;
  }
  const t = userText.toLowerCase();
  return (
    /\b(baaki\s*hai|baki\s*hai|udhaar|udha|उधार|payment\s+due|dues?|outstanding|vasool|vasuli|lene|lena|collect|baki|baaki|due|payment|paisa|paise)\b/i.test(
      t,
    ) &&
    (/\b(baki|baaki|udhaar|due|udha|vasool|vasuli|paisa|payment|lene|lenaa|₹|dues?)\b/i.test(t) ||
      /\b(payment|pay)\b/i.test(t))
  );
}

/** Asks for due lists (today / month / overdue) — not a new collection save. */
function isPaymentDueListQueryText(s: string): boolean {
  const t = s.toLowerCase();
  if (t.length < 6) {
    return false;
  }
  const hasListCue =
    /\b(aaj|aajke|aaj ka|aajka|is\s*maahine|is month|is\s*month|agla|agle|agli|next|overdue|kisko|dues?\s*list|payment\s*list|due\s*list|list|batao|bata|dikha|dikhai|dikhao|kya|kitna|kitne|total|saare?|kaun|kab)\b/i.test(
      t,
    ) || /\b(kaun\s+se|kisko)\b/.test(t);
  const hasPay = /\b(payment|due|baki|vasool|chuk|lane|lena|leni|lene|dues?)\b/i.test(
    t,
  );
  const hasNameAmount = /[\p{L}][\p{L}0-9 .]{1,40}?\s+ka\s+[\d₹,]+/u.test(
    s,
  );
  return hasListCue && hasPay && !hasNameAmount;
}

/**
 * Short generic "record a due" with no client/amount and no time/list scope — ask for details (step 7).
 */
function isBareGenericPaymentDueQuestion(s: string): boolean {
  const t = s
    .toLowerCase()
    .replace(/satyam\s*sir,?\s*/g, "")
    .trim();
  if (t.length < 6 || t.length > 80) {
    return false;
  }
  if (isPaymentDueListQueryText(s) || tryExtractManualPaymentForFirestore(s) != null) {
    return false;
  }
  if (
    /\b(aaj|kal|is\s*maahine|is\s*month|next|agla|kaun|kab|dikha|dikhai|batao|list|mujhe|₹|rupee|client|naam|total|kitna)\b/i.test(
      t,
    )
  ) {
    return false;
  }
  if (/\d{3,}/.test(s) || /[\u20B9]/.test(s)) {
    return false;
  }
  if (
    /[\p{L}][\p{L}0-9 .]{0,32}\s+ka\s+(?:payment|pay|baki|udhaar|udha|₹|rupee|paisa|paise)/u.test(
      s,
    )
  ) {
    return false;
  }
  return (
    t.split(/\s+/).length <= 8 &&
    /\b(manual\s+)?payment\s*(due|baki|baaki|hai|hain|chahiye|leni|lenaa)\b/i.test(
      t,
    )
  );
}

function isManualCollectionReminderText(userText: string): boolean {
  if (isDispatchRecordText(userText) || isRuleOrderCreateText(userText)) {
    return false;
  }
  if (isRuleQuotationText(userText)) {
    return false;
  }
  if (
    isTodayOrderStatsQuestion(userText) ||
    isDispatchStatsQuestion(userText) ||
    isDispatchAggregateCountQuestion(userText)
  ) {
    return false;
  }
  if (isPaymentDueListQueryText(userText)) {
    return false;
  }
  return (
    tryExtractManualPaymentForFirestore(userText) !== null ||
    tryExtractManualCollectionReminder(userText) !== null ||
    isExplicitGenericPaymentReminderText(userText) ||
    isGenericPaymentDueIntentText(userText) ||
    hasLoosePaymentCollectionIntent(userText)
  );
}

async function markPendingPaymentsAndLinkedRemindersPaid(
  uid: string,
  clientKey: string,
  nowMs: number,
): Promise<boolean> {
  const db = getFirestore();
  let docs: QueryDocumentSnapshot<DocumentData>[] = [];
  try {
    const snap = await db
      .collection("users")
      .doc(uid)
      .collection("payments")
      .orderBy("createdAtMs", "desc")
      .limit(60)
      .get();
    docs = snap.docs;
  } catch (e) {
    logger.warn("markPendingPaymentsAndLinkedRemindersPaid: orderBy failed", {
      err: e instanceof Error ? e.message : String(e),
    });
    const snap = await db
      .collection("users")
      .doc(uid)
      .collection("payments")
      .limit(120)
      .get();
    docs = snap.docs;
  }
  const normKey = (d: DocumentData): string =>
    normalizeClientNameKey(
      String(
        (d as { clientKey?: string }).clientKey ??
          (d as { clientName?: string }).clientName ??
          d.client ??
          "",
      ),
    );
  const pending = docs.filter((doc) => {
    const d = doc.data() as DocumentData;
    if (normKey(d) !== clientKey) {
      return false;
    }
    const st = String(d.status ?? "pending").trim().toLowerCase();
    return st !== "paid" && st !== "completed" && st !== "cancelled";
  });
  pending.sort(
    (a, b) =>
      (Number((b.data() as { createdAtMs?: number }).createdAtMs) || 0) -
      (Number((a.data() as { createdAtMs?: number }).createdAtMs) || 0),
  );
  if (pending.length === 0) {
    return false;
  }
  const target = pending[0]!;
  await target.ref.update({
    status: "paid",
    updatedAtMs: nowMs,
    paidAtMs: nowMs,
    paidAt: FieldValue.serverTimestamp(),
  });
  const rsnap = await db
    .collection("users")
    .doc(uid)
    .collection("reminders")
    .where("paymentId", "==", target.id)
    .get();
  if (!rsnap.empty) {
    const wb = db.batch();
    let batchOps = 0;
    for (const r of rsnap.docs) {
      wb.update(r.ref, { status: "completed", updatedAtMs: nowMs });
      batchOps += 1;
    }
    if (batchOps > 0) {
      await wb.commit();
    }
  }
  scheduleRebuildClientStats(uid);
  return true;
}

