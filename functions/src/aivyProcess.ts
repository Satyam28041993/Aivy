async function tryManualCollectionReminder(
  uid: string,
  userText: string,
  timeContext: TimeContext,
): Promise<AivyProcessResponse | null> {
  if (isQuestionIntentText(userText.toLowerCase(), userText)) {
    return null;
  }
  if (!isManualCollectionReminderText(userText)) {
    return null;
  }
  let extracted = tryExtractManualPaymentForFirestore(userText);
  if (extracted === null) {
    const legacy = tryExtractManualCollectionReminder(userText);
    if (legacy) {
      extracted = {
        displayClient: legacy.displayClient,
        amount: legacy.amount,
        days: legacy.days,
      };
    }
  }
  if (extracted === null) {
    if (hasLoosePaymentCollectionIntent(userText)) {
      const rawClient = extractManualClientDisplayName(userText);
      const amt0 = extractManualPaymentInrAmount(userText);
      if (rawClient && (!Number.isFinite(amt0) || amt0 <= 0)) {
        return buildOrderQuotationShortReplyResponse("Kitna rupay / amount batao.", {
          intent: "manual_payment_reminder",
        });
      }
      if (!rawClient && Number.isFinite(amt0) && amt0 > 0) {
        return buildOrderQuotationShortReplyResponse(
          "Kis client / naam ka entry hai? Naam batao.",
          { intent: "manual_payment_reminder" },
        );
      }
    }
    if (isExplicitGenericPaymentReminderText(userText)) {
      return buildOrderQuotationShortReplyResponse("Client aur amount bataiye.", {
        intent: "manual_payment_reminder",
      });
    }
    if (isGenericPaymentDueIntentText(userText)) {
      return buildOrderQuotationShortReplyResponse(
        "Satyam Sir, kis client ka payment due hai aur kitna rupay? Naam aur amount batao.",
        { intent: "manual_payment_reminder" },
      );
    }
    return null;
  }
  if (!Number.isFinite(extracted.amount) || extracted.amount <= 0) {
    return buildOrderQuotationShortReplyResponse("Client aur amount bataiye.", {
      intent: "manual_payment_reminder",
    });
  }
  const { displayClient, amount, days: _days } = extracted;
  void _days;
  const ru = formatInrAmount(amount);
  const userLine = `Samjha: ₹${ru} (${displayClient}) — abhi system mein auto-save nahi; app se confirm karenge.`;
  return buildOrderQuotationShortReplyResponse(userLine, {
    intent: "manual_payment_reminder",
    clientName: displayClient,
    reminderSuggestions: [],
  });
}

async function tryHandlePendingOrderDispatchSelection(
  uid: string,
  userText: string,
  timeContext: TimeContext,
): Promise<AivyProcessResponse | null> {
  const pending = await readPendingOrderDispatchSelection(uid);
  if (!pending) {
    return null;
  }
  const nOrders = pending.orderDocIds.length;
  if (pending.createdAtMs > 0) {
    const ageMs = Date.now() - pending.createdAtMs;
    if (ageMs > DISPATCH_SELECTION_TTL_MS) {
      return buildOrderQuotationShortReplyResponse(SELECT_ORDER_CLARIFY);
    }
  }
  const idx1 = parseSelectionFromText(userText, nOrders);
  if (idx1 === null) {
    if (couldBeNewOrderOrDispatchCommand(userText)) {
      return null;
    }
    if (isMarkOrderPaymentReceivedText(userText)) {
      return null;
    }
    if (isManualCollectionReminderText(userText)) {
      return null;
    }
    return buildOrderQuotationShortReplyResponse(SELECT_ORDER_CLARIFY);
  }
  const docId = pending.orderDocIds[idx1 - 1];
  if (!docId) {
    return null;
  }
  const ref = getFirestore()
    .collection("users")
    .doc(uid)
    .collection("orders")
    .doc(docId);
  const doc = await ref.get();
  if (!doc.exists) {
    return buildOrderQuotationShortReplyResponse(
      "Order record nahi mila. Dubara se order dispatch karein.",
    );
  }
  const data = doc.data() as DocumentData;
  if (!isOrderDocPendingForDispatch(data)) {
    return buildOrderQuotationShortReplyResponse(
      "Yeh order pehle hi dispatch ho chuka hai.",
    );
  }
  const amount = coalesceNumber(data.amount);
  const displayName =
    String(
      (data as { clientName?: string }).clientName ??
        (data as { client?: string }).client ??
        "",
    ).trim() || pending.clientName;
  void ref;
  void docId;
  const line = `Parsed dispatch: ${displayName} (₹${formatInrAmount(amount)}) — auto-save off; confirm in app.`;
  return buildOrderQuotationShortReplyResponse(line, {
    intent: "order_dispatched",
    showBadge: false,
    clientName: displayName,
    reminderSuggestions: [],
  });
}

function buildOrderQuotationShortReplyResponse(
  userReply: string,
  options?: {
    intent?: AivyProcessIntent;
    clientName?: string;
    data?: AivyDataPayload;
    showBadge?: boolean;
    reminderSuggestions?: ReminderSuggestion[];
  },
): AivyProcessResponse {
  const line = sanitizeUserFacingText(userReply);
  const rem = options?.reminderSuggestions ?? [];
  return {
    ...pgplFields(
      options?.intent !== undefined ? { intent: options.intent } : undefined,
    ),
    ...(options?.data !== undefined ? { data: options.data } : {}),
    ...(options?.showBadge === true ? { showBadge: true } : {}),
    contextType: "note",
    category: "work",
    memoryCategory: "general",
    clientName: options?.clientName?.trim() ?? "",
    summary: line,
    keyPoints: [],
    actionItems: [],
    followUpSuggestions: [],
    reminderSuggestions: rem,
    assistantReply: line,
    userReply: line,
    message: line,
  };
}

/**
 * True when text matches rule order / dispatch / quotation patterns (strict path; no Gemini).
 */
function isRuleOrderDispatchOrQuotationText(userText: string): boolean {
  return (
    isRuleOrderCreateText(userText) ||
    isRuleDispatchText(userText) ||
    isRuleQuotationText(userText)
  );
}

/**
 * Order / dispatch / quotation / today's order stats using rule-based parsing (no model intent).
 * Execution order: stats question first, then order create, dispatch, quotation. No broad
 * "relevance" gate before these — that gate used to drop valid Hinglish order lines to Gemini.
 */
async function tryRuleBasedOrderQuotationFirst(
  uid: string,
  userText: string,
  timeContext: TimeContext,
): Promise<AivyProcessResponse | null> {
  const fromSelection = await tryHandlePendingOrderDispatchSelection(
    uid,
    userText,
    timeContext,
  );
  if (fromSelection) {
    return fromSelection;
  }
  const markPaid = await tryMarkClientOrderPaymentReceived(uid, userText);
  if (markPaid) {
    return markPaid;
  }
  if (isBareGenericPaymentDueQuestion(userText)) {
    // eslint-disable-next-line no-console
    console.log("PAYMENT_INTENT", { kind: "query", sub: "bare_clarify" });
    return buildOrderQuotationShortReplyResponse(
      "Kaunse client ka aur kitna amount?",
      { intent: "manual_payment_reminder" },
    );
  }
  const isOrder = isRuleOrderCreateText(userText);
  const isDispatchRecord = isDispatchRecordText(userText);
  const isDispatchStats = isDispatchStatsQuestion(userText);
  const isQuote = isRuleQuotationText(userText);
  // eslint-disable-next-line no-console
  console.log("TEXT:", userText);
  // eslint-disable-next-line no-console
  console.log("ORDER:", isOrder);
  // eslint-disable-next-line no-console
  console.log("DISPATCH_RECORD:", isDispatchRecord);
  // eslint-disable-next-line no-console
  console.log("DISPATCH_STATS:", isDispatchStats);
  // eslint-disable-next-line no-console
  console.log("QUOTATION:", isQuote);
  logger.info("ruleEngine order-quotation", {
    textPreview: userText.slice(0, 200),
    ORDER: isOrder,
    DISPATCH_RECORD: isDispatchRecord,
    DISPATCH_STATS: isDispatchStats,
    QUOTATION: isQuote,
  });

  if (isTodayOrderStatsQuestion(userText)) {
    const data = await runDataIntentQuery(
      uid,
      timeContext,
      "total_orders_today",
    );
    return buildDataDrivenAivyResponse("total_orders_today", data);
  }
  if (isQuotationStatsQuestion(userText)) {
    const unified = classifyAnalyticsRequest(userText, timeContext);
    if (unified) {
      const k = unified.kind;
      if (
        k === "quotation_count" ||
        k === "quotation_value" ||
        k === "quotation_names" ||
        k === "quotation_line_items"
      ) {
        const data = await runAnalyticsRequest(uid, timeContext, unified);
        if (data.analyticsKind) {
          return buildDataDrivenAivyResponse("analytics_query", data);
        }
      }
    }
  }
  if (isDispatchStats) {
    if (isDispatchDetailListIntent(userText)) {
      const unified = classifyAnalyticsRequest(userText, timeContext);
      let lineReq: AnalyticsRequest | null = null;
      if (unified?.kind === "dispatch_line_items") {
        lineReq = unified;
      } else if (unified?.kind === "dispatch_names") {
        lineReq = { ...unified, kind: "dispatch_line_items" };
      } else {
        const win = parseTimeWindow(userText, timeContext, {});
        lineReq = { kind: "dispatch_line_items", window: win };
      }
      const data = await runAnalyticsRequest(uid, timeContext, lineReq);
      if (data.analyticsKind) {
        return buildDataDrivenAivyResponse("analytics_query", data);
      }
    }
    const data = await runDataIntentQuery(
      uid,
      timeContext,
      "dispatches_today",
    );
    return buildDataDrivenAivyResponse("dispatches_today", data);
  }
  if (isDispatchRecord) {
    const { client } = extractRuleClientAndAmount(userText);
    if (!client || client === "Unknown") {
      return buildOrderQuotationShortReplyResponse(
        "Kis client ka order dispatch hua? Naam batao.",
      );
    }
    const displayClient = capitalizeName(client);
    const pendingDocs = await fetchPendingOrderDocsForClient(uid, client);
    if (pendingDocs.length === 0) {
      return buildOrderQuotationShortReplyResponse(
        `No pending orders found for ${displayClient}.`,
      );
    }
    if (pendingDocs.length === 1) {
      const d = pendingDocs[0]!;
      const data = d.data() as DocumentData;
      const amount = coalesceNumber(data.amount);
      const displayName =
        String(
          (data as { clientName?: string }).clientName ??
            (data as { client?: string }).client ??
            "",
        ).trim() || displayClient;
      const line = `Parsed dispatch: ${displayName} (₹${formatInrAmount(amount)}) — auto-save off; confirm in app.`;
      return buildOrderQuotationShortReplyResponse(line, {
        intent: "order_dispatched",
        showBadge: false,
        clientName: displayName,
        reminderSuggestions: [],
      });
    }
    const n = pendingDocs.length;
    const orderRows: Array<{ index: number; amount: number; date: string }> = [];
    const listLines: string[] = [];
    for (let i = 0; i < pendingDocs.length; i++) {
      const docSnap = pendingDocs[i]!;
      const raw = docSnap.data() as DocumentData;
      const amount = coalesceNumber(raw.amount);
      const dateLabel = formatOrderListDate(
        orderDocCreatedAtMs(raw),
        timeContext,
      );
      const idx = i + 1;
      orderRows.push({ index: idx, amount, date: dateLabel || "—" });
      listLines.push(
        `${idx}. ₹${formatInrAmount(amount)}${dateLabel ? ` (${dateLabel})` : ""}`,
      );
    }
    const listBlock = listLines.join("\n");
    const line = `${displayClient} ke ${n} pending orders hain:

${listBlock}

Kaunsa dispatch karna hai? Number batao.`;
    return buildOrderQuotationShortReplyResponse(line, {
      intent: "select_order_for_dispatch",
      clientName: displayClient,
      data: {
        client: displayClient,
        orders: orderRows,
      },
    });
  }
  if (isOrder) {
    const { client, amount } = extractRuleClientAndAmount(userText);
    if (
      !client ||
      client === "Unknown" ||
      !Number.isFinite(amount) ||
      amount <= 0
    ) {
      return buildOrderQuotationShortReplyResponse(OQ_REPHRASE);
    }
    const displayClient = capitalizeName(client);
    const line = `Parsed order: ₹${formatInrAmount(amount)} from ${displayClient} — not saved yet; confirm in app.`;
    return buildOrderQuotationShortReplyResponse(line, {
      intent: "order_create",
      clientName: displayClient,
    });
  }
  if (isQuote) {
    const { client, amount } = extractRuleClientAndAmount(userText);
    if (
      !client ||
      client === "Unknown" ||
      !Number.isFinite(amount) ||
      amount <= 0
    ) {
      return buildOrderQuotationShortReplyResponse(OQ_REPHRASE);
    }
    const displayClient = capitalizeName(client);
    const line = `Parsed quotation: ₹${formatInrAmount(amount)} for ${displayClient} — not saved yet; confirm in app.`;
    return buildOrderQuotationShortReplyResponse(line);
  }
  return null;
}

