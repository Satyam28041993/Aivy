function nowInUserZone(timeContext: TimeContext): DateTime {
  const n = DateTime.fromISO(timeContext.nowIso, { setZone: true });
  if (n.isValid) {
    const z = timeContext.timezone || "UTC";
    return n.setZone(z);
  }
  return DateTime.now().setZone(timeContext.timezone || "UTC");
}

/**
 * "Today" for payment filters: one calendar day in the user zone (same day/month/year as [nowIso] in that zone).
 */
function todayStartEndMs(timeContext: TimeContext): { start: number; end: number } {
  const wall = nowInUserZone(timeContext);
  const s = wall.startOf("day");
  const e = wall.endOf("day");
  return { start: s.toMillis(), end: e.toMillis() };
}

/** Strict same calendar day in the user IANA zone (day + month + year). */
function isSameLocalCalendarDay(
  dueDateMs: number,
  timeContext: TimeContext,
): boolean {
  if (!Number.isFinite(dueDateMs) || dueDateMs <= 0) {
    return false;
  }
  const z = timeContext.timezone?.trim() || "UTC";
  const ref = nowInUserZone(timeContext);
  const ymdRef = ref.toISODate();
  const ymdDue = DateTime.fromMillis(dueDateMs, { zone: "UTC" })
    .setZone(z)
    .toISODate();
  return Boolean(ymdRef && ymdDue && ymdRef === ymdDue);
}

function currentMonthStartEndMs(timeContext: TimeContext): { start: number; end: number } {
  const wall = nowInUserZone(timeContext);
  const start = wall.startOf("month");
  const end = wall.endOf("month");
  return { start: start.toMillis(), end: end.toMillis() };
}

function documentCreatedMs(d: DocumentData): number {
  const ms = Number(d.createdAtMs);
  if (Number.isFinite(ms) && ms > 0) {
    return ms;
  }
  const c = d.createdAt;
  if (c && typeof (c as { toMillis?: () => number }).toMillis === "function") {
    return (c as { toMillis: () => number }).toMillis();
  }
  return 0;
}

/** Epoch ms from Firestore `number` or `Timestamp` (avoids `Number(Timestamp)` → NaN). */
function readEpochMsFromFirestoreValue(v: unknown): number {
  if (typeof v === "number" && Number.isFinite(v) && v > 0) {
    return v;
  }
  if (v && typeof (v as { toMillis?: () => number }).toMillis === "function") {
    const m = (v as { toMillis: () => number }).toMillis();
    if (Number.isFinite(m) && m > 0) {
      return m;
    }
  }
  return 0;
}

function readReminderScheduledMs(d: DocumentData): number {
  const a = readEpochMsFromFirestoreValue(
    (d as { scheduledTimeMs?: unknown }).scheduledTimeMs,
  );
  if (a > 0) {
    return a;
  }
  const b = readEpochMsFromFirestoreValue(
    (d as { scheduledTime?: unknown }).scheduledTime,
  );
  if (b > 0) {
    return b;
  }
  return readEpochMsFromFirestoreValue((d as { remindAt?: unknown }).remindAt);
}

/** Payment due instant: prefer explicit `dueDateMs`, else notification schedule fields. */
function readReminderDueMs(d: DocumentData): number {
  const dm = readEpochMsFromFirestoreValue(
    (d as { dueDateMs?: unknown }).dueDateMs,
  );
  if (dm > 0) {
    return dm;
  }
  return readReminderScheduledMs(d);
}

