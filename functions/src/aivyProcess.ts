type TimeContext = {
  timezone: string;
  nowIso: string;
  localHuman: string;
  todayDate: string;
  offset: string;
  /** User "now" converted to Asia/Kolkata (IST) for payment +30d and PGPL date math. */
  istNowIso: string;
  istLocalHuman: string;
  istTodayDate: string;
};

/**
 * Resolves a reliable "now in the user's timezone" using luxon.
 * Prefers the caller-provided nowIso (which may already carry an offset) and
 * falls back to the current server time zoned into `timezone`.
 * If the timezone is invalid, quietly degrades to UTC.
 */
function buildTimeContext({
  timezone,
  nowIso,
}: {
  timezone?: string;
  nowIso?: string;
}): TimeContext {
  const zoneRaw = timezone?.trim() || "";
  const zoneCandidateAttempt = DateTime.now().setZone(zoneRaw);
  const zoneIsValid = zoneCandidateAttempt.isValid;
  if (!zoneIsValid && zoneRaw) {
    logger.warn("Invalid IANA timezone received, falling back to UTC", { timezone: zoneRaw });
  }
  const effectiveZone = zoneIsValid ? zoneRaw : "UTC";

  let now: DateTime = zoneIsValid ? zoneCandidateAttempt : DateTime.utc();
  if (nowIso) {
    const fromIso = DateTime.fromISO(nowIso, { setZone: true });
    if (fromIso.isValid) {
      const needsRezone =
        effectiveZone && fromIso.zoneName === "UTC" && !nowIso.endsWith("Z");
      const rezoned = needsRezone ? fromIso.setZone(effectiveZone) : fromIso;
      if (rezoned.isValid) {
        now = rezoned;
      }
      if (effectiveZone && now.isValid && now.zoneName !== effectiveZone) {
        const adjusted = now.setZone(effectiveZone);
        if (adjusted.isValid) {
          now = adjusted;
        }
      }
    }
  }

  const resolvedZone = now.isValid ? (now.zoneName || zoneRaw || "UTC") : "UTC";
  const human = now.isValid
    ? now.toFormat("cccc, dd LLLL yyyy 'at' h:mm a '('ZZ')'")
    : DateTime.utc().toISO() ?? "";

  const istWall = now.isValid
    ? now.setZone("Asia/Kolkata")
    : DateTime.now().setZone("Asia/Kolkata");
  const istNowIso = istWall.isValid
    ? (istWall.toISO() ?? new Date().toISOString())
    : new Date().toISOString();
  const istLocalHuman = istWall.isValid
    ? istWall.toFormat("cccc, dd LLLL yyyy 'at' h:mm a '('ZZ')'")
    : "";
  const istTodayDate = istWall.isValid ? (istWall.toISODate() ?? "") : "";

  return {
    timezone: resolvedZone,
    nowIso: now.isValid ? (now.toISO() ?? new Date().toISOString()) : new Date().toISOString(),
    localHuman: human,
    todayDate: now.isValid ? now.toISODate() ?? "" : "",
    offset: now.isValid ? now.toFormat("ZZ") : "Z",
    istNowIso,
    istLocalHuman,
    istTodayDate,
  };
}

