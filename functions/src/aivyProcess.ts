/** Maps /3, *3, Q3, 3 → the same phrasing the classifiers expect. */
function expandAnalyticsCommandShortcut(raw: string): string {
  const s0 = raw.trim();
  if (s0.length < 1) {
    return raw;
  }
  let n: number | null = null;
  const m1 = s0.match(/^\s*\/\s*(\d{1,2})\s*$/);
  const m2 = s0.match(/^\s*\*\s*(\d{1,2})\s*$/);
  const m3 = s0.match(/^\s*Q\s*(\d{1,2})\s*$/i);
  const m4 = s0.match(/^\s*(\d{1,2})\s*$/);
  if (m1) {
    n = parseInt(m1[1]!, 10);
  } else if (m2) {
    n = parseInt(m2[1]!, 10);
  } else if (m3) {
    n = parseInt(m3[1]!, 10);
  } else if (m4) {
    n = parseInt(m4[1]!, 10);
  }
  if (n != null && n >= 1 && n <= 11) {
    const q = ANALYTICS_SHORTCUTS[n];
    if (q) {
      return q;
    }
  }
  return raw;
}

