/**
 * Payment-due list time windows (Hinglish + English).
 * Intentionally separate from [parseTimeWindow]: here "kal" means tomorrow; dispatch stats keep yesterday.
 */
function getPaymentAnalyticsTimeWindow(
  text: string,
  timeContext: TimeContext,
): TimeWindow {
  const raw = text.trim();
  const t = raw.toLowerCase();
  const wall = nowInUserZone(timeContext);
  const nowMs = Date.now();
  const dayMs = 24 * 60 * 60 * 1000;

  if (
    /\b(overdue|over\s*due|late|abhi\s*tak\s*(?:nahi|na)|vasool\s*nahi|chukaya\s*nahi|due\s*ho\s*chuke|pichhla\s*due|purana\s*due|delay)\b/i.test(
      t,
    ) &&
    /\b(payment|due|baki|vasool|vasuli|follow|remind|chuk|lene|collection|bacha)\b/i.test(
      t,
    )
  ) {
    // eslint-disable-next-line no-console
    console.log("PAYMENT_FILTER", { kind: "query", window: "overdue" });
    return { startMs: 0, endMs: nowMs, label: "overdue" };
  }

  // Next calendar month (must run before "is month" / mahine to avoid any overlap with "this month" phrasing)
  if (
    /\bnext\s+month\b/i.test(t) ||
    /\b(agla|agle|agli)\s+(mahina|maahine|month|mahine)\b/i.test(t) ||
    /\b(mahine|month)\s+(ka|ke|ki)\s+agla\b/i.test(t)
  ) {
    const nm0 = wall.startOf("month").plus({ months: 1 });
    const s = nm0.startOf("month");
    const e = nm0.endOf("month");
    // eslint-disable-next-line no-console
    console.log("PAYMENT_FILTER", { kind: "query", window: "nextMonth", label: "agle mahina" });
    return {
      startMs: s.toMillis(),
      endMs: e.toMillis(),
      label: "agle mahina",
    };
  }

  if (
    /\b(is\s*maahine|is mahine|is month|this month|current month|poora mahina|pura month|maheene|masik|महीने|mahine me)\b/i.test(
      t,
    ) ||
    (/\b(is\s*month|monthly)\b/i.test(t) &&
      !/\bnext\s*month\b/i.test(t) &&
      /\b(due|payment|baki|vasool|lena|leni|bhugtan|chuk)\b/.test(t)) ||
    (/\bmahine\b/i.test(t) &&
      !/\b(agla|agle|agli|next|pichh|pichle|pichhle|guzr|guzre|pehle|last|pichhla)\b/i.test(
        t,
      ) &&
      /\b(due|payment|baki|vasool|lena|leni|bhugtan|chuk|kitna|total|list)\b/.test(
        t,
      ))
  ) {
    const { start, end } = currentMonthStartEndMs(timeContext);
    // eslint-disable-next-line no-console
    console.log("PAYMENT_FILTER", { kind: "query", window: "currentMonth", label: "is maahine" });
    return { startMs: start, endMs: end, label: "is maahine" };
  }

  if (/\b(is\s*hafte|is week|this week|week me|hafte)\b/i.test(t)) {
    const { start, end } = currentWeekStartEndMs(timeContext);
    return { startMs: start, endMs: end, label: "is hafte" };
  }

  if (/\b(aaj|aajke|aaj ke|today|aajka|aaj ka)\b/i.test(t)) {
    const { start, end } = todayStartEndMs(timeContext);
    // eslint-disable-next-line no-console
    console.log("PAYMENT_FILTER", { kind: "query", window: "today", label: "aaj" });
    return { startMs: start, endMs: end, label: "aaj" };
  }

  if (
    /\b(yesterday|guzra|guzre|beeta|beeti|pichhla din|kal\s+guzra|kal\s+beeta)\b/i.test(
      t,
    )
  ) {
    const d = wall.minus({ days: 1 });
    return {
      startMs: d.startOf("day").toMillis(),
      endMs: d.endOf("day").toMillis(),
      label: "guzra kal",
    };
  }

  if (
    /\b(kal|tomorrow)\b/i.test(t) &&
    !/\b(aaj|today)\b/i.test(t) &&
    !/\b(pichhle|pichle|guzra|guzre|yesterday)\b/i.test(t)
  ) {
    const tom = wall.plus({ days: 1 });
    return {
      startMs: tom.startOf("day").toMillis(),
      endMs: tom.endOf("day").toMillis(),
      label: "kal",
    };
  }

  const mFwdA = t.match(
    /\b(?:agle|agla|agli|next)\s+(\d{1,2})\s*(?:din|day|days?|dino|dine)\b/i,
  );
  const mFwdB = t.match(
    /\b(\d{1,2})\s*(?:din|day|days?|dino)\s*(?:ke|ki|and|me|main)?\s*(?:and|\/|ya)?\s*(?:agle|aage|aane|forward)\b/i,
  );
  const nFwd = mFwdA
    ? parseInt(mFwdA[1]!, 10)
    : mFwdB
      ? parseInt(mFwdB[1]!, 10)
      : 0;
  if (nFwd >= 1 && nFwd <= 60) {
    return {
      startMs: nowMs,
      endMs: nowMs + nFwd * dayMs,
      label: `agle ${nFwd} din`,
    };
  }

  const mA = t.match(
    /\b(?:pichhle|pichle|guzre|guzar|last)\s*(\d{1,2})\s*(?:din|day|dino|dine)\b/,
  );
  const mB = t.match(
    /\b(\d{1,2})\s*(?:din|day|dino|dine)\s*(?:ke|and|me|main|men|ma|में|mein)\b/,
  );
  const mC = t.match(/\b(\d{1,2})\s*(?:dine|din|day)\s*(?:ke|and|me|ma)\b/);
  const nPast = mA
    ? parseInt(mA[1]!, 10)
    : mB
      ? parseInt(mB[1]!, 10)
      : mC
        ? parseInt(mC[1]!, 10)
        : 0;
  if (nPast >= 1 && nPast <= 60) {
    const endD = wall.endOf("day");
    const startD = wall.minus({ days: nPast - 1 }).startOf("day");
    return {
      startMs: startD.toMillis(),
      endMs: endD.toMillis(),
      label: `pichhle ${nPast} din`,
    };
  }

  if (
    /\b(kab\s+due|total|kul)\b/.test(t) ||
    /\b(baaki|baki|pending|outstanding)\b/.test(t) ||
    /\bsab\b/.test(t)
  ) {
    return {
      startMs: 0,
      endMs: nowMs + 20 * 365 * dayMs,
      label: "sab",
    };
  }

  return {
    startMs: 0,
    endMs: nowMs + 20 * 365 * dayMs,
    label: "sab",
  };
}

/**
 * Resolves a reporting window: month, N-day lookback, kal, aaj, is hafte, or default.
 * `defaultFullYearForPaymentDues`: for payment-balance questions with no explicit day/month,
 * use a wide window (0 → now+365d) instead of defaulting to "today" only.
 */
function parseTimeWindow(
  text: string,
  timeContext: TimeContext,
  opts?: { defaultFullYearForPaymentDues?: boolean },
): TimeWindow {
  const t = text.toLowerCase().trim();
  const wall = nowInUserZone(timeContext);

  if (
    /\b(is\s*maahine|is mahine|is month|this month|current month|poora mahina|pura month|maheene|masik|महीने|mahine me)\b/i.test(
      t,
    ) ||
    (/\b(is\s*month|mahine|monthly)\b/i.test(t) &&
      /quot|qout|order|dispatch|kitne|diya|value|total|bata|due|payment/.test(t))
  ) {
    const { start, end } = currentMonthStartEndMs(timeContext);
    return { startMs: start, endMs: end, label: "is maahine" };
  }
  if (/\b(is\s*hafte|is week|this week|aaj.*week|week me|hafte)\b/i.test(t)) {
    const { start, end } = currentWeekStartEndMs(timeContext);
    return { startMs: start, endMs: end, label: "is hafte" };
  }
  if (
    opts?.defaultFullYearForPaymentDues &&
    (/\bkab\s+due\b/.test(t) ||
      /\btotal\b/.test(t) ||
      /\b(baaki|baki|pending)\b/.test(t)) &&
    !/\b(aaj|aajke|aaj ke|today|aajka|aaj ka)\b/i.test(t) &&
    !/\b(is\s*maahine|is mahine|is month|this month|current month|poora mahina|pura month|maheene|masik|महीने|mahine me)\b/i.test(
      t,
    ) &&
    !/\babhi\s*tak\b/.test(t)
  ) {
    const endMs = Date.now() + 365 * 24 * 60 * 60 * 1000;
    return { startMs: 0, endMs, label: "sab" };
  }
  if (
    /\b(overdue|over\s*due|late|abhi\s*tak\s*(?:nahi|na)|vasool\s*nahi|chukaya\s*nahi|due\s*ho\s*chuke|pichhla\s*due|purana\s*due|delay)\b/i.test(
      t,
    ) &&
    /\b(payment|due|baki|vasool|vasuli|follow|remind|chuk|lene|collection|bacha)\b/.test(
      t,
    )
  ) {
    const startOfToday = wall.startOf("day");
    return {
      startMs: 0,
      endMs: Math.max(0, startOfToday.toMillis() - 1),
      label: "overdue",
    };
  }
  const mA = t.match(
    /\b(?:pichhle|pichle|guzre|guzar|last)\s*(\d{1,2})\s*(?:din|day|dino|dine)\b/,
  );
  const mB = t.match(
    /\b(\d{1,2})\s*(?:din|day|dino|dine)\s*(?:ke|and|me|main|men|ma|में|mein)\b/,
  );
  const mC = t.match(
    /\b(\d{1,2})\s*(?:dine|din|day)\s*(?:ke|and|me|ma)\b/,
  );
  const nFrom = mA
    ? parseInt(mA[1], 10)
    : mB
      ? parseInt(mB[1], 10)
      : mC
        ? parseInt(mC[1], 10)
        : 0;
  if (nFrom >= 1 && nFrom <= 60) {
    const endD = wall.endOf("day");
    const startD = wall.minus({ days: nFrom - 1 }).startOf("day");
    return {
      startMs: startD.toMillis(),
      endMs: endD.toMillis(),
      label: `pichhle ${nFrom} din`,
    };
  }
  if (/\b(kal|yesterday|guccha)\b/i.test(t) && !/\b(aaj|today)\b/i.test(t)) {
    const d = wall.minus({ days: 1 });
    const start = d.startOf("day");
    const end = d.endOf("day");
    return { startMs: start.toMillis(), endMs: end.toMillis(), label: "kal" };
  }
  if (/\b(aaj|aajke|aaj ke|today|aajka|aaj ka)\b/i.test(t)) {
    const { start, end } = todayStartEndMs(timeContext);
    return { startMs: start, endMs: end, label: "aaj" };
  }
  if (/\babhi\s*tak\b/.test(t)) {
    const { start, end } = todayStartEndMs(timeContext);
    return { startMs: start, endMs: end, label: "aaj" };
  }
  if (opts?.defaultFullYearForPaymentDues) {
    const endMs = Date.now() + 365 * 24 * 60 * 60 * 1000;
    return { startMs: 0, endMs, label: "sab" };
  }
  const { start, end } = todayStartEndMs(timeContext);
  return { startMs: start, endMs: end, label: "aaj" };
}

