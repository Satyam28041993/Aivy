async function processWithGemini({
  uid,
  text,
  timeContext,
  geminiKey,
  memoryContext,
  userProfile,
  rawFirestoreMemory,
  sessionMemoryLines,
  dualDispatchPaymentIntent = false,
  forceScheduleReminder = false,
  searchResults,
}: {
  uid: string;
  text: string;
  timeContext: TimeContext;
  geminiKey: string;
  memoryContext?: string;
  userProfile: AivyUserProfile;
  rawFirestoreMemory: Record<string, unknown>;
  sessionMemoryLines: string[];
  dualDispatchPaymentIntent?: boolean;
  forceScheduleReminder?: boolean;
  searchResults?: SearchResultItem[];
}): Promise<GeminiStructuredProcessOutcome> {
  const systemPrompt = buildMergedAivySystemPrompt(
    userProfile,
    sessionMemoryLines,
    rawFirestoreMemory,
  );
  const jsonInstruction = buildGeminiJsonSystemInstruction(timeContext, {
    dualDispatchPaymentIntent,
    forceScheduleReminder,
  });
  const timeAndPgplMemory = buildTimeAndInternalMemoryContext(
    timeContext,
    memoryContext,
  );

  let searchContext = "";
  if (searchResults && searchResults.length > 0) {
    const searchBlock = searchResults
      .map((r, i) => `[${i + 1}] Title: "${r.title}", Link: "${r.link}", Snippet: "${r.snippet}"`)
      .join("\n");
    searchContext = `\n\nLIVE GOOGLE SEARCH RESULTS:\n${searchBlock}\n\nINSTRUCTION: Use these live Google search results to answer the user's question accurately. Prioritize this information for real-world factual questions. Summarize clearly.\n`;
  }

  const combinedPrompt = `${systemPrompt}

${jsonInstruction}

${timeAndPgplMemory}${searchContext}
User: ${text}

Return ONLY valid JSON.`;

  const payload = {
    contents: [
      {
        role: "user",
        parts: [{ text: combinedPrompt }],
      },
    ],
  };
  logger.info("PAYLOAD SENT TO GEMINI:", JSON.stringify(payload));

  let response: Response;
  try {
    response = await fetchGeminiGenerateContentWithRetry(
      geminiKey,
      JSON.stringify(payload),
    );
  } catch (e) {
    logger.error("Gemini fetch failed after retries (processWithGemini)", {
      err: e instanceof Error ? e.message : String(e),
    });
    return {
      fromStructuredModelJson: false,
      response: await buildCompanionPlainFallbackResponse(
        uid,
        text,
        timeContext,
        geminiKey,
        userProfile,
        sessionMemoryLines,
        rawFirestoreMemory,
      ),
    };
  }

  if (!response.ok) {
    const err = await response.text().catch(() => "");
    logger.error("Gemini generateContent failed (processWithGemini): non-OK HTTP", {
      status: response.status,
      statusText: response.statusText,
      preview: err.slice(0, 800),
    });
    return {
      fromStructuredModelJson: false,
      response: await buildCompanionPlainFallbackResponse(
        uid,
        text,
        timeContext,
        geminiKey,
        userProfile,
        sessionMemoryLines,
        rawFirestoreMemory,
      ),
    };
  }

  let data: GeminiGenerateContentResponse;
  try {
    data = (await response.json()) as GeminiGenerateContentResponse;
  } catch (e) {
    logger.error("Invalid JSON envelope from Gemini (structured path)", {
      err: e instanceof Error ? e.message : String(e),
    });
    return {
      fromStructuredModelJson: false,
      response: await buildCompanionPlainFallbackResponse(
        uid,
        text,
        timeContext,
        geminiKey,
        userProfile,
        sessionMemoryLines,
        rawFirestoreMemory,
      ),
    };
  }

  const modelTextPart =
    data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
  const modelText =
    modelTextPart.trim().length > 0
      ? modelTextPart
      : textFromGenerateContent(data);

  if (!modelText.trim()) {
    logger.error("No Gemini message content (structured JSON path)");
    return {
      fromStructuredModelJson: false,
      response: await buildCompanionPlainFallbackResponse(
        uid,
        text,
        timeContext,
        geminiKey,
        userProfile,
        sessionMemoryLines,
        rawFirestoreMemory,
      ),
    };
  }

  let rawText = modelText.trim();

  // Remove markdown if exists
  rawText = rawText.replace(/```json/g, "").replace(/```/g, "").trim();

  // Extract JSON if extra text exists
  const jsonStart = rawText.indexOf("{");
  const jsonEnd = rawText.lastIndexOf("}");

  if (jsonStart !== -1 && jsonEnd !== -1) {
    rawText = rawText.substring(jsonStart, jsonEnd + 1);
  }

  let parsed: Record<string, unknown>;
  let innerJsonOk = true;
  try {
    parsed = JSON.parse(rawText) as Record<string, unknown>;
  } catch (e) {
    innerJsonOk = false;
    logger.error("JSON PARSE ERROR (model output)", {
      err: e instanceof Error ? e.message : String(e),
      preview: rawText.slice(0, 400),
    });
    const dataFromIntent = await tryDataDrivenResponse(uid, timeContext, text);
    if (dataFromIntent) {
      return { fromStructuredModelJson: false, response: dataFromIntent };
    }
    parsed = {
      intent: "general",
      jobRecord: {
        client: "",
        amount: 0,
        status: "pending" as const,
        invoiceAmount: 0,
      },
      paymentRecord: { client: "", amount: 0, dueDateIso: "" },
      assistantReply:
        "I understood your request but couldn’t structure it properly.",
      userReply: "Something went wrong while processing.",
    };
  }

  parsed.summary ??= "";
  parsed.actionItems ??= [];

  const memUp = parsed["userMemoryUpdate"];
  if (
    memUp &&
    typeof memUp === "object" &&
    !Array.isArray(memUp) &&
    memUp !== null
  ) {
    try {
      await saveUserMemory(uid, memUp as Record<string, unknown>);
    } catch (e) {
      logger.error("saveUserMemory (from model) failed", {
        uid,
        err: e instanceof Error ? e.message : String(e),
      });
    }
  }

  normalizeParsedGeminiPayload(parsed);

  if (forceScheduleReminder) {
    const rems = parsed.reminderSuggestions;
    if (!Array.isArray(rems) || rems.length === 0) {
      parsed.reminderSuggestions = [buildFallbackReminderSuggestion(text, timeContext)];
    }
  }

  const sanitized = sanitizeModelResponse(parsed, timeContext);

  return {
    fromStructuredModelJson: innerJsonOk,
    response: sanitized,
  };
}

