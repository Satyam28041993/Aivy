/**
 * "Ramesh ka payment kab due" → "ramesh" key; null when no per-client scoping in the phrase.
 */
function extractClientKeyFromPaymentQueryText(text: string): string | null {
  const t = text.trim();
  if (t.length < 2) {
    return null;
  }
  const noise = new Set([
    "total",
    "kaun",
    "kitna",
    "kitne",
    "aaj",
    "kal",
    "sab",
    "all",
    "pura",
    "poora",
  ]);
  const m1 = t.match(
    /^\s*([\p{L}][\p{L}0-9 .]{0,48}?)\s+ka\s+(?:\u20B9\s*)?(?:payment|pay)\b/iu,
  );
  if (m1) {
    const name = m1[1]!.replace(/\s+/g, " ").trim();
    if (name.length >= 2 && !noise.has(normalizeClientNameKey(name))) {
      return normalizeClientNameKey(name);
    }
  }
  const m2 = t.match(
    /\b([\p{L}][\p{L}0-9 .]{0,30}?)\s+ka\s+(?:\u20B9\s*)?(?:payment|pay)\b[^?]*\bkab\b/iu,
  );
  if (m2) {
    const name = m2[1]!.replace(/\s+/g, " ").trim();
    if (name.length >= 2 && !noise.has(normalizeClientNameKey(name))) {
      return normalizeClientNameKey(name);
    }
  }
  const m3 = t.match(
    /\b([\p{L}][\p{L}0-9 .]{0,40}?)\s+ka\s+kitna\b[^.!?]{0,80}?\b(baaki|baki|outstanding|pending|dues?|bacha|bacha|collect|vasool|vasuli)\b/iu,
  );
  if (m3) {
    const name = m3[1]!.replace(/\s+/g, " ").trim();
    if (name.length >= 2 && !noise.has(normalizeClientNameKey(name))) {
      return normalizeClientNameKey(name);
    }
  }
  const m4 = t.match(
    /\b([\p{L}][\p{L}0-9 .]{0,40}?)\s+se[^.!?\n]{0,60}?(?:\u20B9|rs\.?|rupee|lenaa?|lene|leni|vasool|vasuli|baki|baaki|payment|pay)/iu,
  );
  if (m4) {
    const name = m4[1]!.replace(/\s+/g, " ").trim();
    if (name.length >= 2 && !noise.has(normalizeClientNameKey(name))) {
      return normalizeClientNameKey(name);
    }
  }
  const m5 = t.match(
    /\b([\p{L}][\p{L}0-9 .]{0,48}?)\s+ka\s+(?:\u20B9\s*)?(?:payment|pay)\b(?:\s+[\p{L}]{1,12}){0,6}\s*(?:due|hai|hain|he|ho|kab)\b/iu,
  );
  if (m5) {
    const name = m5[1]!.replace(/\s+/g, " ").trim();
    if (name.length >= 2 && !noise.has(normalizeClientNameKey(name))) {
      return normalizeClientNameKey(name);
    }
  }
  return null;
}

function paymentClientLabel(client: string): string {
  const t = client.trim();
  if (!t || t === "Client") {
    return "Unknown";
  }
  return t;
}

function resolvePaymentRowDueMs(row: PaymentDueRow): number {
  if (Number.isFinite(row.dueMs) && row.dueMs > 0) {
    return row.dueMs;
  }
  return 0;
}

/**
 * `users/.../payments` rows only, pending, filtered by [dueDateMs] in window.
 */
async function queryPaymentRowsDueInWindow(
  uid: string,
  startMs: number,
  endMs: number,
  timeContext: TimeContext,
): Promise<PaymentDueRow[]> {
  const zone = timeContext.timezone?.trim() || "Asia/Kolkata";
  const payDocs = await getPaymentsByDateRange(uid, startMs, endMs);
  const merged: PaymentDueRow[] = [];
  for (const doc of payDocs) {
    const d = doc.data() as DocumentData;
    const dueMs = paymentDueMsFromDocument(d);
    if (dueMs <= 0) {
      continue;
    }
    const client = paymentClientLabel(
      String(
        (d as { clientName?: string }).clientName ?? d.client ?? "",
      ).trim() || "Client",
    );
    const ck = String(
      (d as { clientKey?: string }).clientKey ?? normalizeClientNameKey(client),
    ).trim() || normalizeClientNameKey(client);
    const dueDateIso =
      DateTime.fromMillis(dueMs, { zone: "UTC" })
        .setZone(zone)
        .toISO() ?? "";
    const oid = String((d as { orderId?: string }).orderId ?? "").trim();
    merged.push({
      client,
      clientKey: normalizeClientNameKey(ck) || normalizeClientNameKey(client),
      amount: openDueRollupAmount(d),
      dueDateIso,
      dueMs,
      orderId: oid || undefined,
      recordId: `pay:${doc.id}`,
    });
  }
  merged.sort((a, b) => a.dueMs - b.dueMs);
  // eslint-disable-next-line no-console
  console.log("PAYMENT QUERY RESULT", { count: merged.length, startMs, endMs });
  logger.info("PAYMENT QUERY RESULT", { uid, count: merged.length, startMs, endMs });
  return merged;
}

/** Pending reminders scheduled up to end of local today (includes overdue). */
async function queryPendingRemindersDueThroughEndOfToday(
  uid: string,
  timeContext: TimeContext,
  endTodayMs: number,
): Promise<Array<{ client: string; amount: number; dueMs: number; dueDateLabel: string }>> {
  if (!Number.isFinite(endTodayMs) || endTodayMs <= 0) {
    return [];
  }
  const db = getFirestore();
  const snap = await db
    .collection("users")
    .doc(uid)
    .collection("reminders")
    .where("status", "==", "pending")
    .where("scheduledTimeMs", "<=", endTodayMs)
    .orderBy("scheduledTimeMs", "asc")
    .limit(200)
    .get();
  const out: Array<{ client: string; amount: number; dueMs: number; dueDateLabel: string }> = [];
  for (const doc of snap.docs) {
    const d = doc.data() as DocumentData;
    const ms = readReminderScheduledMs(d);
    if (ms <= 0 || ms > endTodayMs) {
      continue;
    }
    const raw = String(d.title ?? d.message ?? "Reminder").trim() || "Reminder";
    const client = raw.length > 100 ? `${raw.slice(0, 97)}…` : raw;
    let dueDateLabel = formatDueDateShortForUser(timeContext, ms);
    if (!dueDateLabel || dueDateLabel === "—") {
      const z = timeContext.timezone?.trim() || "Asia/Kolkata";
      dueDateLabel =
        DateTime.fromMillis(ms, { zone: "UTC" }).setZone(z).toFormat("d LLL, h:mm a") ||
        "—";
    }
    out.push({
      client,
      amount: 0,
      dueMs: ms,
      dueDateLabel,
    });
  }
  return out;
}

