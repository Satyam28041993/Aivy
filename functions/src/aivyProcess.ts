/**
 * Authoritative due for filtering: `dueDateMs`, else paymentDueDateMs, paymentDueDate, or dueDateIso.
 */
function paymentDueMsFromDocument(d: DocumentData): number {
  const n = readEpochMsFromFirestoreValue(
    (d as { dueDateMs?: unknown }).dueDateMs,
  );
  if (n > 0) {
    return n;
  }
  const pdm = readEpochMsFromFirestoreValue(
    (d as { paymentDueDateMs?: unknown }).paymentDueDateMs,
  );
  if (pdm > 0) {
    return pdm;
  }
  const pd = (d as { paymentDueDate?: unknown }).paymentDueDate;
  if (pd && typeof (pd as { toMillis?: () => number }).toMillis === "function") {
    const m = (pd as { toMillis: () => number }).toMillis();
    if (m > 0) {
      return m;
    }
  }
  const iso = (d as { dueDateIso?: string }).dueDateIso;
  if (typeof iso === "string" && iso.trim().length > 0) {
    const m = dueMsFromValidPaymentIsoString(iso.trim());
    if (m != null && m > 0) {
      return m;
    }
  }
  return 0;
}

/**
 * After dispatch: set payment due fields on the order and build UI line + reminder payload.
 * When [opts.defaultCreditDaysIfUnspecified] is set, use it if no credit days are parsed from
 * the user line (e.g. dashboard "Mark as dispatched" with empty text). Chat dispatch keeps
 * 0 days (due today) when the user does not say a number.
 */
async function runOrderDispatchWithPayment(
  userText: string,
  timeContext: TimeContext,
  orderRef: DocumentReference<DocumentData>,
  orderDocId: string,
  displayClient: string,
  amount: number,
  nowMs: number,
  opts?: { defaultCreditDaysIfUnspecified?: number },
): Promise<{
  line: string;
  reminder: ReminderSuggestion;
}> {
  let days = extractPaymentDaysForDispatch(userText);
  if (
    days === 0 &&
    opts?.defaultCreditDaysIfUnspecified != null &&
    opts.defaultCreditDaysIfUnspecified > 0
  ) {
    days = opts.defaultCreditDaysIfUnspecified;
  }
  const base = nowInUserZone(timeContext);
  const at = base
    .plus({ days })
    .set({ hour: 10, minute: 0, second: 0, millisecond: 0 });
  const paymentDueDateMs = at.toMillis();
  const dueLabel = formatDueDateShortForUser(timeContext, paymentDueDateMs);
  const scheduledAtIso = at.isValid
    ? (at.toISO() ?? new Date().toISOString())
    : new Date().toISOString();
  const ru = formatInrAmount(amount);
  const note = `Payment follow-up for ${displayClient} ₹${ru}`;
  await orderRef.update({
    status: "dispatched",
    dispatchDate: FieldValue.serverTimestamp(),
    dispatchedAt: FieldValue.serverTimestamp(),
    dispatchedAtMs: nowMs,
    updatedAtMs: nowMs,
    paymentStatus: "pending",
    paymentDueDate: Timestamp.fromMillis(paymentDueDateMs),
    paymentDueDateMs,
    paymentReminderCreated: true,
  });
  const par = orderRef.parent.parent;
  if (!par) {
    throw new Error("runOrderDispatchWithPayment: missing user id");
  }
  const uid = par.id;
  const { id: paymentId } = await createPaymentEntry(uid, {
    clientName: displayClient,
    amount,
    dueDateMs: paymentDueDateMs,
    source: "dispatch",
    orderId: orderDocId,
  });
  // eslint-disable-next-line no-console
  console.log("REMINDER LINKED", { paymentId, orderId: orderDocId });
  logger.info("REMINDER LINKED", { uid, paymentId, orderId: orderDocId });
  const reminder: ReminderSuggestion = {
    title: note,
    timeHint: `${days} din credit`,
    priority: "high",
    scheduledAtIso,
    isAutoGenerated: true,
    reminderType: "payment_followup",
    orderId: orderDocId,
    orderAmountInr: amount,
    displayClientName: displayClient,
    note,
    paymentId,
  };
  const line = `Satyam Sir, ₹${ru} wala order dispatch ho gaya.\nPayment follow-up ${days} din baad (${dueLabel}) ke liye set kar diya hai.`;
  return { line, reminder };
}

