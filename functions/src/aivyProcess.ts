/** Time / IST + PGPL subcollection "business memory" (quotations, entries, tasks). No user line. */
function buildTimeAndInternalMemoryContext(
  timeContext: TimeContext,
  memoryContext?: string,
): string {
  const { timezone, nowIso, todayDate, istNowIso, istLocalHuman, istTodayDate } =
    timeContext;
  const monthKey = todayDate.length >= 7 ? todayDate.slice(0, 7) : "";
  const istMonthKey =
    istTodayDate.length >= 7 ? istTodayDate.slice(0, 7) : monthKey;
  const memoryBlock = memoryContext?.trim()
    ? `\n\nInternal memory context (PGPL quotations / entries / tasks; silent):
${memoryContext.trim()}

Use when relevant. If it conflicts with the latest User: line, trust the User: line.`
    : "";
  return `User timezone (IANA): ${timezone}
Current time (ISO): ${nowIso}
Current calendar month key (yyyy-MM): ${monthKey}

IST now (ISO, Asia/Kolkata): ${istNowIso}
IST now (human, Asia/Kolkata): ${istLocalHuman}
IST calendar month key (yyyy-MM): ${istMonthKey}${memoryBlock}`;
}

function buildGeminiUserTurn(
  text: string,
  timeContext: TimeContext,
  memoryContext?: string,
): string {
  return `${buildTimeAndInternalMemoryContext(timeContext, memoryContext)}

User: ${text}`;
}

function safeSingleLine(value: unknown): string {
  return String(value ?? "")
    .replace(/\s+/g, " ")
    .trim();
}

