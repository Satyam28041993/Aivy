/** True when the model only parrots the user line instead of answering. */
function replyEchoesUserInput(reply: string, userText: string): boolean {
  const a = reply.trim().toLowerCase().replace(/\s+/g, " ");
  const b = userText.trim().toLowerCase().replace(/\s+/g, " ");
  if (!a || !b) {
    return false;
  }
  if (a === b) {
    return true;
  }
  if (a.length >= 8 && b.length >= 8 && (b.includes(a) || a.includes(b))) {
    const ratio = Math.min(a.length, b.length) / Math.max(a.length, b.length);
    return ratio > 0.72;
  }
  return false;
}

