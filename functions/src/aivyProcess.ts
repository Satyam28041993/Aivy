async function tryDataDrivenResponse(
  uid: string,
  timeContext: TimeContext,
  userText: string,
): Promise<AivyProcessResponse | null> {
  const textForAnalytics = expandAnalyticsCommandShortcut(userText);
  const clientInsights = classifyClientInsightsRequest(textForAnalytics, timeContext);
  if (clientInsights) {
    try {
      const data = await runAnalyticsRequest(uid, timeContext, clientInsights);
      if (data.analyticsKind) {
        return buildDataDrivenAivyResponse("analytics_query", data);
      }
    } catch (e) {
      logger.error("Client insights (Phase 3) query failed", {
        uid,
        err: e instanceof Error ? e.message : String(e),
      });
    }
  }
  const unified = classifyAnalyticsRequest(textForAnalytics, timeContext);
  if (unified) {
    try {
      const data = await runAnalyticsRequest(uid, timeContext, unified);
      if (!data.analyticsKind) {
        return null;
      }
      logger.info("Unified analytics resolved", {
        uid,
        kind: data.analyticsKind,
        label: data.windowLabel,
      });
      return buildDataDrivenAivyResponse("analytics_query", data);
    } catch (e) {
      logger.error("Unified analytics query failed", {
        uid,
        err: e instanceof Error ? e.message : String(e),
      });
      return null;
    }
  }
  const intent = detectDataIntentFromText(textForAnalytics);
  if (!intent) {
    return null;
  }
  let data: AivyDataPayload;
  try {
    data = await runDataIntentQuery(uid, timeContext, intent);
  } catch (e) {
    logger.error("Data intent Firestore query failed", {
      uid,
      intent,
      err: e instanceof Error ? e.message : String(e),
    });
    return null;
  }
  logger.info("Data-driven intent resolved", { uid, intent, data });
  return buildDataDrivenAivyResponse(intent, data);
}

