function isOrderDocPendingForDispatch(data: DocumentData): boolean {
  const st = String(data.status ?? "").trim().toLowerCase();
  if (st === "dispatched") {
    return false;
  }
  if (st === "cancelled" || st === "canceled") {
    return false;
  }
  if (st === "pending" || st === "created") {
    return true;
  }
  if (st) {
    return false;
  }
  const dd = (data as { dispatchDate?: unknown }).dispatchDate;
  if (dd != null) {
    return false;
  }
  const dAt = (data as { dispatchedAtMs?: unknown }).dispatchedAtMs;
  if (dAt != null && Number(dAt) > 0) {
    return false;
  }
  return true;
}

function orderDocCreatedAtMs(d: DocumentData): number {
  const m = d.createdAtMs;
  if (typeof m === "number" && Number.isFinite(m)) {
    return m;
  }
  if (typeof m === "string" && m.trim()) {
    const p = Number(m);
    if (Number.isFinite(p)) {
      return p;
    }
  }
  const ca = d.createdAt as { toMillis?: () => number } | undefined;
  if (ca && typeof ca.toMillis === "function") {
    return ca.toMillis();
  }
  return 0;
}

function formatOrderListDate(createdAtMs: number, timeContext: TimeContext): string {
  if (!Number.isFinite(createdAtMs) || createdAtMs <= 0) {
    return "";
  }
  const zone = timeContext.timezone?.trim() || "UTC";
  const dt = DateTime.fromMillis(createdAtMs, { zone: "UTC" }).setZone(zone);
  if (!dt.isValid) {
    return "";
  }
  return dt.toFormat("d LLL");
}

function formatDueDateShortForUser(
  timeContext: TimeContext,
  dueAtMs: number,
): string {
  if (!Number.isFinite(dueAtMs) || dueAtMs <= 0) {
    return "—";
  }
  const zone = timeContext.timezone?.trim() || "UTC";
  const dt = DateTime.fromMillis(dueAtMs, { zone: "UTC" }).setZone(zone);
  if (!dt.isValid) {
    return "—";
  }
  return dt.toFormat("d LLL");
}

function formatInrListAmount(n: number): string {
  const r = Math.round(n);
  return r.toLocaleString("en-IN");
}

/**
 * One strict list format for payment-due output (server + must stay aligned with client).
 * Grouped by client to avoid a duplicate-looking run of the same name.
 * Format: [Client] then one line per row: ₹Amount — Due date
 */
function formatPaymentList(
  rows: Array<{ client: string; amount?: number; dueDateLabel?: string }>,
  opts?: { totalAmount?: number; showTotalFromQuery?: string },
): string {
  if (rows.length === 0) {
    return "Koi payment due nahi hai";
  }
  const wantTotalLine =
    opts?.totalAmount != null &&
    opts.totalAmount > 0 &&
    opts?.showTotalFromQuery != null &&
    /\btotal\b/i.test(opts.showTotalFromQuery);
  const byClient = new Map<
    string,
    Array<{ client: string; amount?: number; dueDateLabel?: string }>
  >();
  for (let i = 0; i < Math.min(rows.length, 40); i++) {
    const r = rows[i]!;
    const c = (r.client || "Unknown").trim() || "Unknown";
    if (!byClient.has(c)) {
      byClient.set(c, []);
    }
    byClient.get(c)!.push(r);
  }
  const lines: string[] = [];
  if (wantTotalLine) {
    lines.push(
      `Total ₹${formatInrListAmount(opts!.totalAmount!)} payment due hai\n`,
    );
  }
  for (const [client, list] of byClient) {
    lines.push(client);
    for (const r of list.slice(0, 20)) {
      const a = Number.isFinite(r.amount) ? r.amount! : 0;
      const d = (r.dueDateLabel || "Due date pending").trim();
      lines.push(`₹${formatInrListAmount(a)} — ${d}`);
    }
  }
  return lines.join("\n");
}

